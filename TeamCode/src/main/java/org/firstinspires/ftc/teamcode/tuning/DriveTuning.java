    @Override
    public void confirm(String title, String message, Display display) throws InterruptedException {
        freshPresses();
        while (!gamepad1.crossWasPressed()) {
            checkStop();
            partHeader();
            g.html("<b>" + Guide.escape(title) + "</b>");
            g.doThis(message);
            picture(display);
            g.keys("cross = continue");
            g.update();
        }
        busy();
    }

    @Override
    public void ask(Inputs inputs, Display display) throws InterruptedException {
        List<Inputs.Field<?>> open = new ArrayList<>();
        for (Inputs.Field<?> f : inputs.fields()) {
            if (KNOWN.containsKey(f.name)) f.set(convert(f, KNOWN.get(f.name)));
            else open.add(f);
        }
        if (open.isEmpty()) return;
        freshPresses();
        int selected = 0;
        String note = "";
        while (true) {
            checkStop();
            if (gamepad1.dpadUpWasPressed()) selected = Math.max(0, selected - 1);
            if (gamepad1.dpadDownWasPressed()) selected = Math.min(open.size() - 1, selected + 1);
            int change = (gamepad1.dpadRightWasPressed() ? 1 : 0) - (gamepad1.dpadLeftWasPressed() ? 1 : 0);
            if (change != 0) {
                change(open.get(selected), change, gamepad1.left_bumper);
                note = "";
            }
            if (gamepad1.crossWasPressed()) {
                String missing = "";
                for (Inputs.Field<?> f : open) if (f.get() == null) missing = f.name;
                if (missing.isEmpty()) {
                    busy();
                    return;
                }
                note = "choose an answer for \"" + missing + "\" (dpad left / right)";
            }
            partHeader();
            g.html("<b>" + Guide.escape(inputs.name) + "</b>");
            if (!inputs.description.equals(inputs.name)) g.say(inputs.description);
            picture(display);
            for (int i = 0; i < open.size(); i++) {
                Inputs.Field<?> f = open.get(i);
                String line = f.name + ": " + show(f);
                if (i == selected) g.html("<b>&gt; " + Guide.escape(line) + "</b>");
                else g.say("  " + line);
            }
            if (!note.isEmpty()) g.warn(note);
            g.keys((open.size() > 1 ? "dpad up / down = choose a line, " : "") + "dpad left / right = change it"
                    + (hasNumber(open) ? " (hold L1 = steps of 10)" : "") + ", cross = OK");
            g.update();
        }
    }

    @Override
    public void stepStart(TuningOpMode<?> step, Display display) throws InterruptedException {
        stepDone = false;
        stepLines = Collections.emptyList();
        freshPresses();
        while (!gamepad1.crossWasPressed()) {
            checkStop();
            partHeader();
            g.html("<b>NEXT: " + Guide.escape(step.name) + "</b>");
            g.doThis(step.description);
            picture(display);
            g.warn(step.canStop ? "Nothing moves until you do it; press cross to begin, then cross again when done."
                    : "It moves BY ITSELF after cross. Clear the area; STOP always stops it.");
            g.keys("cross = start");
            g.update();
        }
        drawRunning(step);
    }

    @Override
    public boolean stepDone(TuningOpMode<?> step) {
        if (gamepad1.crossWasPressed()) stepDone = true;
        if (System.nanoTime() - lastDrawNs > REDRAW_S * 1e9) drawRunning(step);
        return stepDone;
    }

    @Override
    public void stepTelemetry(TuningOpMode<?> step, List<String> lines) {
        stepLines = lines;
        if (System.nanoTime() - lastDrawNs > REDRAW_S * 1e9) drawRunning(step);
    }

    @Override
    public void result(String key, Object value) {
        String name = RESULT_NAMES.get(key);
        if (name != null) results.put(name, value);
    }

    private void drawRunning(TuningOpMode<?> step) {
        lastDrawNs = System.nanoTime();
        partHeader();
        g.html("<b>NOW: " + Guide.escape(step.name) + "</b>");
        g.doThis(step.description);
        picture(step.display());
        for (String l : stepLines) g.say(l);
        g.keys(step.canStop ? "cross = done (once you have done what it says), STOP = stop" : "running by itself, STOP = stop");
        g.update();
    }

    // shown while Pedro gets the next step ready (it can take a moment), so nobody presses again
    private void busy() {
        partHeader();
        g.say("Getting the next step ready...");
        g.update();
    }

    // a press made before this screen showed (a second press on the last one while the robot was busy) must not
    // count here: above all not as "start" for a step that drives by itself
    private void freshPresses() {
        gamepad1.crossWasPressed();
        gamepad1.dpadUpWasPressed();
        gamepad1.dpadDownWasPressed();
        gamepad1.dpadLeftWasPressed();
        gamepad1.dpadRightWasPressed();
    }

    private void checkStop() throws InterruptedException {
        if (!opModeIsActive()) throw new InterruptedException("stopped");
    }

    // the robot from above with the wheel to watch marked (Pedro's page shows the same as a drawing)
    private void picture(Display display) {
        if (!(display instanceof Display.FourWheelBot)) return;
        Display.FourWheelBot.Wheel w = ((Display.FourWheelBot) display).wheel;
        g.html("<tt>" + pad(4) + "FRONT (intake)</tt>");
        g.html("<tt>" + wheel("FL", w == Display.FourWheelBot.Wheel.FRONT_LEFT) + "-------" + wheel("FR", w == Display.FourWheelBot.Wheel.FRONT_RIGHT) + "</tt>");
        g.html("<tt>" + pad(1) + "|" + pad(10) + "|</tt>");
        g.html("<tt>" + wheel("BL", w == Display.FourWheelBot.Wheel.BACK_LEFT) + "-------" + wheel("BR", w == Display.FourWheelBot.Wheel.BACK_RIGHT) + "</tt>");
        g.say("Watch the " + w.name().toLowerCase(Locale.US).replace('_', ' ') + " wheel. Forward = the top of the wheel rolls toward the FRONT.");
    }

    private static String wheel(String name, boolean marked) {
        return marked ? "<b><font color='#c62828'>[" + name + "]</font></b>" : "[" + name + "]";
    }

    private static String pad(int n) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < n; i++) sb.append(NBSP);
        return sb.toString();
    }

    private static boolean hasNumber(List<Inputs.Field<?>> fields) {
        for (Inputs.Field<?> f : fields) if (f.type == Inputs.Type.DOUBLE || f.type == Inputs.Type.INTEGER) return true;
        return false;
    }

    private static String show(Inputs.Field<?> f) {
        Object v = f.get();
        if (v == null) return "?  (dpad left / right)";
        if (f.type == Inputs.Type.BOOLEAN) return (Boolean) v ? "YES" : "NO";
        if (f.type == Inputs.Type.ENUM) return ((Enum<?>) v).name().toLowerCase(Locale.US).replace('_', ' ');
        if (f.type == Inputs.Type.DOUBLE) return String.format(Locale.US, "%.1f", (Double) v);
        return String.valueOf(v);
    }

    @SuppressWarnings({"unchecked", "rawtypes"})
    private static Object convert(Inputs.Field<?> f, Object value) {
        if (f.type == Inputs.Type.ENUM && value instanceof String) return Enum.valueOf((Class<Enum>) f.enumClass, (String) value);
        return value;
    }

    private static void change(Inputs.Field<?> f, int direction, boolean big) {
        Object v = f.get();
        switch (f.type) {
            case BOOLEAN:
                f.set(v == null || !(Boolean) v);
                break;
            case ENUM: {
                Object[] all = f.enumClass.getEnumConstants();
                int i = v == null ? (direction > 0 ? -1 : 0) : ((Enum<?>) v).ordinal();
                f.set(all[Math.floorMod(i + direction, all.length)]);
                break;
            }
            case DOUBLE: {
                double d = v == null ? 0 : (Double) v;
                f.set(Math.max(0, d + direction * (big ? NUMBER_BIG_STEP : NUMBER_STEP)));
                break;
            }
            case INTEGER: {
                int i = v == null ? 0 : (Integer) v;
                f.set(Math.max(0, i + direction * (big ? (int) NUMBER_BIG_STEP : (int) NUMBER_STEP)));
                break;
            }
            default:
                break;
        }
    }
