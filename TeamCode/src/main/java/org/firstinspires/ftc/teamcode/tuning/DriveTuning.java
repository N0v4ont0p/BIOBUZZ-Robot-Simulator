    @Override
    public void runOpMode() throws InterruptedException {
        g = new Guide(telemetry, 5);
        if (g.missingDevices(this, DeviceNames.LEFT_FRONT, DeviceNames.LEFT_BACK, DeviceNames.RIGHT_FRONT, DeviceNames.RIGHT_BACK,
                DeviceNames.PINPOINT)) return;
        for (LynxModule hub : hardwareMap.getAll(LynxModule.class)) hub.setBulkCachingMode(LynxModule.BulkCachingMode.AUTO);

        while (opModeInInit()) {
            g.header(0, 0, "Pedro's drive tuning, on the Driver Station");
            g.why("Pedro, the path-following library, measures the drive itself: wheel directions, odometry, 17 driving numbers.");
            g.say("No laptop: every question and step is on this screen. Each part saves its numbers on the robot; the next part uses them.");
            g.say("Nothing moves until you press cross on a step. STOP always stops the robot.");
            menu(firstToDo(), false);
            g.doThis("Press START.");
            g.update();
        }
        if (isStopRequested()) return;

        int selected = firstToDo();
        String note = "";
        boolean chained = false;
        while (opModeIsActive()) {
            if (gamepad1.dpadUpWasPressed()) selected = Math.max(0, selected - 1);
            if (gamepad1.dpadDownWasPressed()) selected = Math.min(Part.values().length - 1, selected + 1);
            if (gamepad1.crossWasPressed()) {
                note = runPart(Part.values()[selected]);
                selected = firstToDo();
            }
            if (!chained && allTuned()) {
                chained = true;
                g.loadNextOnStop(this);
            }
            g.header(0, 0, "Drive tuning: pick a part");
            menu(selected, true);
            if (!note.isEmpty()) g.warn(note);
            if (allTuned()) g.good("Parts 1 to 3 done. Press STOP: \"" + g.nextProgram() + "\" loads by itself.");
            g.keys("dpad up / down = choose, cross = run it (a done part runs again)");
            g.update();
        }
    }

    // "" or why the part stopped
    private String runPart(Part p) throws InterruptedException {
        // numbers the parts before saved (a minute ago, no build)
        LiveResults.apply();
        Procedure procedure;
        switch (p) {
            case WHEELS: procedure = new MecanumTuner(); break;
            case PINPOINT: procedure = new PinpointTuner(); break;
            case FORESIGHT:
                if (!Constants.pinpointTuned()) return "Foresight needs part 2 (Pinpoint) first";
                procedure = new ForesightTuner(Constants::localizer, Constants::drivetrain);
                break;
            default:
                if (!Constants.pinpointTuned()) return "Tests need part 2 (Pinpoint) first";
                procedure = new Tests(Constants::drivetrain, Constants::localizer,
                        () -> Constants.foresightTuned() ? new Foresight(Constants.foresightConfig()) : null);
                break;
        }
        part = p;
        results.clear();
        String problem = "";
        try {
            procedure.run(this);
        } catch (Procedure.Aborted e) {
            problem = e.getMessage();
        } catch (InterruptedException | TuningOpMode.Stopped e) {
            throw new InterruptedException("stopped");
        } catch (RuntimeException e) {
            if (isStopRequested()) throw new InterruptedException("stopped");
            problem = "Pedro stopped: " + e.getMessage();
        }
        while (opModeIsActive() && !gamepad1.crossWasPressed()) {
            g.header(p.ordinal() + 1, Part.values().length, p.title);
            if (problem.isEmpty()) {
                g.good("PART " + (p.ordinal() + 1) + " DONE: its numbers are saved on the robot.");
                resultsBlock();
            } else {
                g.warn("STOPPED: " + problem);
                g.doThis("Fix that, then run this part again.");
            }
            g.keys("cross = back to the list");
            g.update();
        }
        if (isStopRequested()) throw new InterruptedException("stopped");
        part = null;
        return problem.isEmpty() ? "" : p.title + ": " + problem;
    }

    private void menu(int selected, boolean marker) {
        Set<String> saved = LiveResults.saved();
        for (Part p : Part.values()) {
            String status = done(p, saved) ? "DONE" : p == Part.TESTS ? "optional" : "to do";
            String line = (p.ordinal() + 1) + " " + p.title + " (" + p.tuner + "): " + status + " - " + p.where;
            if (marker && p.ordinal() == selected) g.html("<b>&gt; " + Guide.escape(line) + "</b>");
            else g.say((marker ? "  " : "") + line);
        }
    }

    private static boolean done(Part p, Set<String> saved) {
        if (p == Part.TESTS) return false;
        if (p == Part.PINPOINT && Constants.pinpointTuned() && !saved.contains("xPodOffset")) return true;
        if (p == Part.FORESIGHT && Constants.foresightTuned() && !saved.contains("brakeKV")) return true;
        for (String k : p.keys) if (!saved.contains(k)) return false;
        return true;
    }

    private static boolean allTuned() {
        Set<String> saved = LiveResults.saved();
        return done(Part.WHEELS, saved) && done(Part.PINPOINT, saved) && done(Part.FORESIGHT, saved);
    }

    private static int firstToDo() {
        Set<String> saved = LiveResults.saved();
        for (Part p : Part.values()) if (p != Part.TESTS && !done(p, saved)) return p.ordinal();
        return Part.TESTS.ordinal();
    }

    private void resultsBlock() {
        if (results.isEmpty()) return;
        g.say("Backup: a photo of this block (the numbers are already in the robot's results file).");
        g.html("<b>RESULTS P5</b>");
        for (Map.Entry<String, Object> e : results.entrySet()) {
            g.html("<tt>" + Guide.escape(e.getKey() + " = " + value(e.getValue())) + "</tt>");
        }
        g.html("<b>END P5</b>");
    }

    private static String value(Object v) {
        return v instanceof Double ? String.format(Locale.US, "%.6g", (Double) v) : String.valueOf(v);
    }

    private void partHeader() {
        g.header(part.ordinal() + 1, Part.values().length, part.title);
    }

