// Generated by refract-suite ftc-construct. PRACTICE ONLY, nothing moves. One screen (and one file,
// /sdcard/FIRST/biobuzz_setup_report.txt) with every number the setup programs and the CAD sheet put into the robot:
// per program each value and where it is (in the code, only in the results file = not built in yet, or missing), the
