package org.firstinspires.ftc.teamcode.subsystems;

import com.qualcomm.robotcore.hardware.DcMotor;
import com.qualcomm.robotcore.hardware.DcMotorEx;
import com.qualcomm.robotcore.hardware.DcMotorSimple;
import com.qualcomm.robotcore.hardware.HardwareMap;
import com.qualcomm.robotcore.hardware.Servo;
import com.qualcomm.robotcore.hardware.VoltageSensor;
import com.qualcomm.robotcore.util.Range;

import org.firstinspires.ftc.teamcode.config.DeviceNames;
import org.firstinspires.ftc.teamcode.config.Tuned;

import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Locale;

// Generated by refract-suite ftc-construct. One flywheel motor + one hood servo + one feed gate servo.
// Two instances: front (NECTAR) and back (POLLEN), each with its own shot table of measured points. The gate holds collected
// elements away from the flywheel and opens only to fire (as DECODE). Nothing moves until commanded (R102).
public class Launcher {
    // set by prerequisites E-4: true if +power spins the wheel against the launch direction
    public static boolean FRONT_REVERSED = false;
    public static boolean BACK_REVERSED = false;
    // the shot table as a curve averaging neighbouring points (ShotCurve); false = straight lines between the points
    public static boolean SMOOTH_CURVE = true;
    // the curve may ask for more speed past the last point: never above this share of the flywheel's top speed
    private static final double SPEED_CAP = 0.95;

    public final String name;
    private final DcMotorEx motor;
    private final Servo hood;
    private final Servo gate;
    private double gateClosed, gateOpen;
    private Boolean gateIsOpen = null;
    public static final int MAX_SHOTS = 16;
    public static final int DISTANCE = 0, SPEED = 1, HOOD = 2, FEED = 3;
    private static final String[] COLUMNS = {"Distance", "Speed", "Hood", "Feed"};
    // ready() must hold this long before a shot: one reading inside the band can be the wheel swinging through it
    private static final double SETTLE_S = 0.15;
    // the hub's velocity control outputs power, so its gains are rescaled for the battery this often
    private static final double VOLTAGE_CHECK_S = 0.5, GAIN_CHANGE = 0.005;

    private double p, i, d, f, band, idle, hoodMin, hoodMax, tunedVolts;
    // the band per speed (7 shot-speed check): at bandLowSpeed and bandHighSpeed; NaN = the one band everywhere
    private double bandLow, bandHigh, bandLowSpeed, bandHighSpeed;
    private double[][] shots;
    private ShotCurve curve;
    private double target = 0;
    private final HardwareMap hardwareMap;
    private final ServoApproach hoodDrive;
    private long readySinceNs = 0, voltageCheckNs = 0;
    private double gainScale = 1;

    private Launcher(HardwareMap hardwareMap, String name, String motorName, String hoodName, String gateName, boolean reversed) {
        this.name = name;
        this.hardwareMap = hardwareMap;
        motor = hardwareMap.get(DcMotorEx.class, motorName);
        hood = hardwareMap.get(Servo.class, hoodName);
        hoodDrive = new ServoApproach(hood);
        gate = hardwareMap.get(Servo.class, gateName);
        motor.setDirection(reversed ? DcMotorSimple.Direction.REVERSE : DcMotorSimple.Direction.FORWARD);
        motor.setMode(DcMotor.RunMode.RUN_USING_ENCODER);
        motor.setZeroPowerBehavior(DcMotor.ZeroPowerBehavior.FLOAT);
    }

    public static Launcher front(HardwareMap hardwareMap) {
        Launcher l = new Launcher(hardwareMap, "front", DeviceNames.FRONT_FLYWHEEL, DeviceNames.FRONT_HOOD, DeviceNames.FRONT_GATE, FRONT_REVERSED);
        l.p = Tuned.frontFlywheelP;
        l.i = Tuned.frontFlywheelI;
        l.d = Tuned.frontFlywheelD;
        l.f = Tuned.frontFlywheelF;
        l.tunedVolts = Tuned.frontFlywheelVoltage;
        l.band = Tuned.frontReadyBand;
        l.bandLow = Tuned.frontReadyBandLow;
        l.bandHigh = Tuned.frontReadyBandHigh;
        l.bandLowSpeed = Tuned.frontReadyBandLowSpeed;
        l.bandHighSpeed = Tuned.frontReadyBandHighSpeed;
        l.idle = Tuned.frontIdleVelocity;
        l.hoodMin = Tuned.frontHoodMin;
        l.hoodMax = Tuned.frontHoodMax;
        l.setShots(shotTable("front"));
        l.gateClosed = Tuned.frontGateClosed;
        l.gateOpen = Tuned.frontGateOpen;
        return l.applyPidf();
    }

    public static Launcher back(HardwareMap hardwareMap) {
        Launcher l = new Launcher(hardwareMap, "back", DeviceNames.BACK_FLYWHEEL, DeviceNames.BACK_HOOD, DeviceNames.BACK_GATE, BACK_REVERSED);
        l.p = Tuned.backFlywheelP;
        l.i = Tuned.backFlywheelI;
        l.d = Tuned.backFlywheelD;
        l.f = Tuned.backFlywheelF;
        l.tunedVolts = Tuned.backFlywheelVoltage;
        l.band = Tuned.backReadyBand;
        l.bandLow = Tuned.backReadyBandLow;
        l.bandHigh = Tuned.backReadyBandHigh;
        l.bandLowSpeed = Tuned.backReadyBandLowSpeed;
        l.bandHighSpeed = Tuned.backReadyBandHighSpeed;
        l.idle = Tuned.backIdleVelocity;
        l.hoodMin = Tuned.backHoodMin;
        l.hoodMax = Tuned.backHoodMax;
        l.setShots(shotTable("back"));
        l.gateClosed = Tuned.backGateClosed;
        l.gateOpen = Tuned.backGateOpen;
        return l.applyPidf();
    }

    private Launcher applyPidf() {
        if (pidfSet()) motor.setVelocityPIDFCoefficients(p * gainScale, i * gainScale, d * gainScale, f * gainScale);
        return this;
    }

    // F was measured at tunedVolts (G-3); at a lower battery the same power gives less speed, so every gain is
    // scaled by tunedVolts / battery now (a few times a second, only when it changed)
    private void compensateVoltage() {
        long now = System.nanoTime();
        if (Double.isNaN(tunedVolts) || !pidfSet() || now - voltageCheckNs < VOLTAGE_CHECK_S * 1e9) return;
        voltageCheckNs = now;
        double volts = 0;
        for (VoltageSensor sensor : hardwareMap.voltageSensor) volts = Math.max(volts, sensor.getVoltage());
        if (volts < 6) return;
        double scale = tunedVolts / volts;
        if (Math.abs(scale - gainScale) > GAIN_CHANGE * gainScale) {
            gainScale = scale;
            applyPidf();
        }
    }

    public boolean pidfSet() {
        return Tuned.isSet(p, i, d, f);
    }

    public boolean readyBandSet() {
        return !Double.isNaN(band);
    }

    public boolean tableSet() {
        return pidfSet() && Tuned.isSet(band, hoodMin, hoodMax) && shots.length >= 2;
    }

    public double[][] shots() {
        return shots;
    }

    public ShotCurve curve() {
        return curve;
    }

    private void setShots(double[][] rows) {
        shots = rows;
        curve = new ShotCurve(rows, SMOOTH_CURVE);
    }

    // the highest speed a table may ask for: 95 % of this flywheel's top speed (from F), unlimited before program 7
    public double speedCap() {
        return Tuned.isSet(f) && f > 0 ? SPEED_CAP * 32767 / f : Double.POSITIVE_INFINITY;
    }

    // Shot from the table at this distance, plus driver offsets used when auto-shooter is off (+ hood offset = hood up).
    public boolean aim(double distance, double velocityOffset, double hoodOffset) {
        if (!tableSet() || Double.isNaN(distance)) {
            stop();
            return false;
        }
        spin(Math.max(0, Math.min(speedCap(), curve.speed(distance)) + velocityOffset));
        setHood(curve.hood(distance) + hoodOffset * hoodUp());
        return true;
    }

    // Data collection (Front / Back Shot Tuner): exact velocity and hood, no table.
    public boolean manual(double velocity, double hoodPosition) {
        if (!pidfSet()) {
            stop();
            return false;
        }
        spin(velocity);
        if (!Double.isNaN(hoodPosition)) setHood(hoodPosition);
        return true;
    }

    // hood range from E-7, or the full servo range until it is measured. A hood servo mounted the other way round
    // has its lowest position above its highest, so the range is put in order first.
    public double clipHood(double position) {
        double a = Double.isNaN(hoodMin) ? 0 : hoodMin, b = Double.isNaN(hoodMax) ? 1 : hoodMax;
        return Range.clip(position, Math.min(a, b), Math.max(a, b));
    }

    // always reached from the low side (ServoApproach), never backed off past the hood's lowest position
    private void setHood(double position) {
        double a = Double.isNaN(hoodMin) ? 0 : hoodMin, b = Double.isNaN(hoodMax) ? 1 : hoodMax;
        hoodDrive.set(clipHood(position), Math.min(a, b));
    }

    // which way a servo step raises the hood: -1 for a hood servo mounted the other way round (min above max)
    public double hoodUp() {
        return hoodMin > hoodMax ? -1 : 1;
    }

    public void idle() {
        if (pidfSet() && !Double.isNaN(idle)) spin(idle);
        else stop();
    }

    public void stop() {
        target = 0;
        motor.setPower(0);
    }

    private void spin(double ticksPerSecond) {
        compensateVoltage();
        target = ticksPerSecond;
        motor.setVelocity(ticksPerSecond);
    }

    public boolean ready() {
        return target > 0 && !Double.isNaN(band) && Math.abs(velocity() - target) <= band(target);
    }

    // The ready band at this target speed: the one band from program 7, or, once the shot-speed check saved a band at the
    // lowest and the highest shot speed, the straight line between them (held at the end values outside them).
    public double band(double speed) {
        if (!Tuned.isSet(bandLow, bandHigh, bandLowSpeed, bandHighSpeed) || bandHighSpeed <= bandLowSpeed || bandLow <= 0 || bandHigh <= 0) return band;
        double t = Range.clip((speed - bandLowSpeed) / (bandHighSpeed - bandLowSpeed), 0, 1);
        return bandLow + t * (bandHigh - bandLow);
    }

    // ready without a break for SETTLE_S; call it every loop
    public boolean steady() {
        if (!ready()) {
            readySinceNs = 0;
            return false;
        }
        long now = System.nanoTime();
        if (readySinceNs == 0) readySinceNs = now;
        return now - readySinceNs >= SETTLE_S * 1e9;
    }

    public double velocity() {
        return motor.getVelocity();
    }

    public double target() {
        return target;
    }

    public double hoodPosition() {
        return hoodDrive.target();
    }

    // Feed power this launcher tolerates at this distance (both DECODE robots fed slower when far; 32008:
    // over-feeding the far shot jams). NaN until the shot table has 2 points (G-5).
    public double feedPower(double distance) {
        if (shots.length < 2 || Double.isNaN(distance)) return Double.NaN;
        return Range.clip(curve.feed(distance), 0.3, 1);
    }

    // the hood range (program 4) is measured
    public boolean hoodRangeSet() {
        return Tuned.isSet(hoodMin, hoodMax);
    }

    public boolean gateSet() {
        return Tuned.isSet(gateClosed, gateOpen);
    }

    // Commands the servo only when the state changes. False until positions are measured (E-8).
    public boolean setGate(boolean open) {
        if (!gateSet()) return false;
        if (gateIsOpen == null || gateIsOpen != open) {
            gate.setPosition(open ? gateOpen : gateClosed);
            gateIsOpen = open;
        }
        return true;
    }

    // Straight line between the two measured points either side of the distance. Outside the measured
    // range it holds the nearest end point (never extrapolates). Rows are sorted by distance. The match uses
    // curve() (ShotCurve), which is this when SMOOTH_CURVE is off.
    public static double lookup(double[][] rows, int column, double distance) {
        double dd = Range.clip(distance, rows[0][DISTANCE], rows[rows.length - 1][DISTANCE]);
        for (int k = 1; k < rows.length; k++) {
            if (dd <= rows[k][DISTANCE]) {
                double[] a = rows[k - 1], b = rows[k];
                double span = b[DISTANCE] - a[DISTANCE];
                double t = span > 0 ? (dd - a[DISTANCE]) / span : 0;
                return a[column] + t * (b[column] - a[column]);
            }
        }
        return rows[rows.length - 1][column];
    }

    // Complete rows of Tuned.<side>ShotNN{Distance,Speed,Hood,Feed}, sorted by distance.
    // the shot table in the code ("front" / "back"), complete rows only, sorted by distance
    public static double[][] shotTable(String side) {
        List<double[]> rows = new ArrayList<>();
        for (int n = 1; n <= MAX_SHOTS; n++) {
            double[] row = new double[COLUMNS.length];
            for (int c = 0; c < COLUMNS.length; c++) {
                row[c] = tuned(String.format(Locale.US, "%sShot%02d%s", side, n, COLUMNS[c]));
            }
            if (Tuned.isSet(row)) rows.add(row);
        }
        Collections.sort(rows, (a, b) -> Double.compare(a[DISTANCE], b[DISTANCE]));
        return rows.toArray(new double[0][]);
    }

    private static double tuned(String field) {
        try {
            return Tuned.class.getField(field).getDouble(null);
        } catch (ReflectiveOperationException e) {
            throw new IllegalStateException("Tuned." + field + " missing: re-run tools/codegen/render.sh", e);
        }
    }
}
