package org.firstinspires.ftc.teamcode.tuning;

import com.pedropathing.math.Pose;
import com.pedropathing.math.Velocity;
import com.qualcomm.hardware.gobilda.GoBildaPinpointDriver;
import com.qualcomm.hardware.lynx.LynxModule;
import com.qualcomm.robotcore.eventloop.opmode.LinearOpMode;
import com.qualcomm.robotcore.eventloop.opmode.TeleOp;
import com.qualcomm.robotcore.util.ElapsedTime;

import org.firstinspires.ftc.robotcore.external.navigation.DistanceUnit;
import org.firstinspires.ftc.teamcode.config.DeviceNames;
import org.firstinspires.ftc.teamcode.config.Field;
import org.firstinspires.ftc.teamcode.config.MatchState;
import org.firstinspires.ftc.teamcode.pedro.Constants;
import org.firstinspires.ftc.teamcode.subsystems.Drive;

import java.util.Locale;

// Generated by refract-suite ftc-construct. PRACTICE ONLY. Setup program 6 (prerequisites E-10, H-0).
// 1: checks the odometry velocity is in field directions (the aim code needs that). 2: sets the tuning
// start position (own GARDEN corner, Field.startPose). 3: a 96 in push along the wall measures the pod wheels'
// real ticks per mm. 4: the robot spins 10 turns by itself and is lined up again: the gyro's heading scale.
// Both are used straight away for the rest of this run. 5, 6: from the corner again, drive a loop and come back;
// the difference shows how well the robot keeps track of where it is.
@TeleOp(name = "6 Position Check", group = "19859 Setup")
public class PositionCheck extends LinearOpMode {
    // check thresholds, not robot measurements
    private static final double PUSH_SPEED = 6.0;           // in/s
    private static final double GOOD_AGREEMENT = 0.9, BAD_AGREEMENT = 0.3;   // cosine of velocity vs movement
    private static final double HOLD_S = 0.3;
    private static final double HEADING_WINDOW_DEG = 20;
    private static final double OK_DISTANCE_IN = 1.0, OK_TURN_DEG = 2.0;
    private static final double MIN_LOOP_S = 15;
    private static final double PUSH_IN = 96, PUSH_LIMIT = 0.05;
    // goBILDA's figure for the 4-bar pods (what the Pinpoint uses until podTicksPerMm is measured)
    private static final double CATALOG_TICKS_PER_MM = 19.89436789;
    private static final int TURNS = 10;
    private static final double SPIN_POWER = 0.5, SPIN_SLOW_POWER = 0.2, SPIN_SLOW_DEG = 90, TURN_LIMIT_DEG = 45;
    private static final int STEPS = 6;

    @Override
    public void runOpMode() {
        Guide g = new Guide(telemetry, 6);
        if (g.missingDevices(this, DeviceNames.LEFT_FRONT, DeviceNames.LEFT_BACK, DeviceNames.RIGHT_FRONT, DeviceNames.RIGHT_BACK,
                DeviceNames.PINPOINT)) return;
        for (LynxModule hub : hardwareMap.getAll(LynxModule.class)) hub.setBulkCachingMode(LynxModule.BulkCachingMode.AUTO);
        Drive drive = new Drive(hardwareMap);
        GoBildaPinpointDriver pinpoint = Constants.pinpoint(hardwareMap);
        MatchState.Alliance alliance = MatchState.alliance;

        while (opModeInInit()) {
            if (gamepad1.squareWasPressed()) alliance = MatchState.Alliance.BLUE;
            if (gamepad1.circleWasPressed()) alliance = MatchState.Alliance.RED;
            drive.update();
            g.header(0, 0, "Before you start");
            String missing = !drive.localized() ? "Pinpoint numbers (program 5, Pinpoint Tuner: they come straight from the results file)"
                    : !Field.cornerReseedReady() ? "robot edge sizes in the code (setup step C-2)" : "";
            if (!missing.isEmpty()) g.notReady(missing);
            g.value("Alliance", alliance == null ? "NONE: press square = blue, circle = red" : alliance.toString());
            g.say("Robot on the floor in open space. You will drive it with the sticks (robot-centric) and push it by hand.");
            g.doThis(alliance == null ? "Pick the alliance, then press START." : "Press START.");
            g.update();
        }
        if (isStopRequested()) return;
        if (!drive.localized() || !Field.cornerReseedReady() || alliance == null) {
            while (opModeIsActive()) {
                g.header(0, 0, "Cannot run");
                g.notReady(!drive.localized() ? "Pinpoint numbers (program 5)" : !Field.cornerReseedReady() ? "robot edge sizes (C-2)" : "alliance (pick it in INIT)");
                g.update();
            }
            return;
        }

        int step = 1;
        boolean velocityPassed = false, velocityFailed = false, recorded = false;
        double goodSince = -1, badSince = -1, lastCheckS = 0;
        Pose lastCheckPose = drive.pose();
        Pose start = null;
        ElapsedTime clock = new ElapsedTime();
        ElapsedTime loopTimer = new ElapsedTime();
        double[] result = null;
        String note = "";
        int spin = 0;                // 10 turns: 0 = line up, 1 = spinning, 2 = line up again
        double turned = 0, lastHeadingDeg = 0;

        while (opModeIsActive()) {
            boolean next = gamepad1.crossWasPressed(), back = gamepad1.triangleWasPressed();
            if (next || back) note = "";
            drive.update();
            Pose pose = drive.pose();
            Velocity v = drive.velocity();
            double headingDeg = Math.toDegrees(pose.heading());
            // every bit of turning, unwrapped (for the 10 turns)
            turned += Field.wrapDeg(headingDeg - lastHeadingDeg);
            lastHeadingDeg = headingDeg;
            if (step == 4 && spin == 1) {
                double left = TURNS * 360 - turned;
                drive.driveFieldCentric(0, 0, left > SPIN_SLOW_DEG ? SPIN_POWER : SPIN_SLOW_POWER, pose.heading());
                if (left <= 0) {
                    drive.stop();
                    spin = 2;
                }
            } else if (step == 1 || step == 6) {
                drive.driveFieldCentric(-gamepad1.left_stick_y * 0.6, gamepad1.left_stick_x * 0.6, -gamepad1.right_stick_x * 0.5, pose.heading());
            } else if (step == 3 || step == 4) {
                // slow, for lining up exactly
                drive.driveFieldCentric(-gamepad1.left_stick_y * 0.3, gamepad1.left_stick_x * 0.3, -gamepad1.right_stick_x * 0.2, pose.heading());
            } else {
                drive.stop();
            }
            // in step 4 triangle belongs to the spin (start over), not to going back a step
            if (back && step > 1 && step <= STEPS && !(step == 4 && spin != 0)) {
                step--;
                result = null;
                spin = 0;
            }

            switch (step) {
                case 1:
                    g.header(1, STEPS, "Odometry direction check");
                    g.why("The turret keeps aiming while you drive and needs the robot's speed in field directions. This proves it.");
                    g.goal("PASS: velocity is in field directions.");
                    g.doThis("Turn the robot (right stick, or by hand) until Heading reads about 90.");
                    g.doThis("Then drive it with the left stick (or push it) in a straight line for a second.");
                    g.value("Heading", String.format(Locale.US, "%.0f deg", headingDeg));
                    g.value("Velocity x / y", String.format(Locale.US, "%.1f / %.1f in/s", v.vx, v.vy));
                    // compare the reported velocity with how the position actually changed; at heading 90 the
                    // field and robot directions differ by 90 degrees, so a robot-relative velocity can't match
                    double speed = Math.hypot(v.vx, v.vy);
                    double dt = clock.seconds() - lastCheckS;
                    double moveX = pose.x() - lastCheckPose.x(), moveY = pose.y() - lastCheckPose.y();
                    double moveSpeed = dt > 0 ? Math.hypot(moveX, moveY) / dt : 0;
                    lastCheckPose = pose;
                    lastCheckS = clock.seconds();
                    boolean facing90 = Math.abs(headingDeg - 90) <= HEADING_WINDOW_DEG;
                    if (facing90 && speed > PUSH_SPEED && moveSpeed > PUSH_SPEED / 2) {
                        double agree = (v.vx * moveX + v.vy * moveY) / (speed * Math.hypot(moveX, moveY));
                        boolean good = agree >= GOOD_AGREEMENT;
                        boolean bad = agree <= BAD_AGREEMENT;
                        if (good) {
                            if (goodSince < 0) goodSince = clock.seconds();
                            if (clock.seconds() - goodSince >= HOLD_S) velocityPassed = true;
                        } else {
                            goodSince = -1;
                        }
                        if (bad) {
                            if (badSince < 0) badSince = clock.seconds();
                            if (clock.seconds() - badSince >= HOLD_S) velocityFailed = true;
                        } else {
                            badSince = -1;
                        }
                    } else {
                        goodSince = -1;
                        badSince = -1;
                    }
                    if (velocityPassed) g.good("PASS: velocity is in field directions.");
                    if (velocityFailed && !velocityPassed) g.warn("FAIL: velocity follows the robot, not the field. Tell the programmer.");
                    g.keys(velocityPassed || velocityFailed ? "cross = next" : "drive in a straight line at heading 90 first");
                    if (next && (velocityPassed || velocityFailed)) {
                        note = g.record("velocityFrame", velocityPassed ? "field" : "robot");
                        g.record("velocityFrameField", velocityPassed ? "1" : "0");
                        step++;
                    }
                    break;
                case 2:
                case 5:
                    g.header(step, STEPS, step == 2 ? "Put the robot in the start position" : "Back to the start position");
                    g.why("The Pinpoint only measures movement, so it is told the starting spot once.");
                    g.goal("Back and right side flat against the two walls.");
                    g.say("Stand behind your alliance wall, looking at the field. Use the corner on your RIGHT");
                    g.say("(your GARDEN corner; take any POLLEN out).");
                    g.doThis("Back of the robot flat against your alliance wall.");
                    g.doThis("Right side flat against the side wall.");
                    g.doThis("Front (intake) pointing straight across the field, away from you.");
                    g.keys("cross = the robot is in place, triangle = back");
                    if (next) {
                        start = Field.startPose(alliance);
                        drive.setPose(start);
                        loopTimer.reset();
                        step++;
                    }
                    break;
                case 3: {
                    double moved = Math.hypot(pose.x() - start.x(), pose.y() - start.y());
                    g.header(3, STEPS, "Pod scale: 96 in along the wall");
                    g.why("Pod wheels are never exactly their catalog size: 1% off is 1 in for every 100 in driven. This measures them.");
                    g.goal("Exactly 96 in (8 ft) from where it started, straight along the wall.");
                    g.doThis("Lay a tape measure along the side wall with 0 at the robot's back edge.");
                    g.doThis("Push the robot (or drive it slowly) straight forward, right side touching the wall, until its back edge is at 96 in. Then cross.");
                    g.value("Pinpoint says", String.format(Locale.US, "%.2f in", moved));
                    g.keys("cross = back edge at 96 in, triangle = back");
                    if (next) {
                        double ratio = moved / PUSH_IN;
                        if (Math.abs(ratio - 1) > PUSH_LIMIT) {
                            note = String.format(Locale.US, "it says %.1f in: push it exactly 96 in. Still way off: a pod is slipping or lifted, check them", moved);
                        } else {
                            double used = Double.isNaN(Constants.podTicksPerMm) ? CATALOG_TICKS_PER_MM : Constants.podTicksPerMm;
                            double measured = used * ratio;
                            // used for the rest of this run; the code gets it from the results file
                            pinpoint.setEncoderResolution(measured, DistanceUnit.MM);
                            note = g.record("podTicksPerMm", String.format(Locale.US, "%.5f", measured));
                            step++;
                        }
                    }
                    break;
                }
                case 4:
                    g.header(4, STEPS, "Heading scale: 10 turns");
                    g.why("The Pinpoint's gyro reads a few tenths of a percent off. Over a match that adds up to degrees of aim.");
                    g.goal("After 10 turns it faces exactly the way it started.");
                    if (spin == 0) {
                        g.doThis("Drive it to open space (2 ft from any wall). Line the robot's front edge up with a straight tile seam or a strip of tape.");
                        g.doThis("Hands and cables clear: press cross and it spins 10 turns by itself.");
                        g.keys("cross = spin, triangle = back");
                        if (next) {
                            turned = 0;
                            spin = 1;
                        }
                    } else if (spin == 1) {
                        g.say("Spinning... (STOP stops it)");
                        g.value("Turns", String.format(Locale.US, "%.1f of %d", turned / 360, TURNS));
                    } else {
                        g.doThis("Turn it back (slowly with the right stick, or by hand) until its front edge lines up with the SAME seam, the same way round. Then cross.");
                        g.value("Pinpoint says", String.format(Locale.US, "%.1f deg (%.2f turns)", turned, turned / 360));
                        g.keys("cross = lined up again, triangle = start over");
                        if (back) spin = 0;
                        if (next) {
                            double truth = TURNS * 360;
                            if (Math.abs(turned - truth) > TURN_LIMIT_DEG) {
                                note = String.format(Locale.US, "it says %.0f deg, but 10 turns are 3600: line it up the same way round as at the start", turned);
                            } else {
                                double scalar = pinpoint.getYawScalar() * truth / turned;
                                pinpoint.setYawScalar(scalar);
                                note = g.record("imuYawScalar", String.format(Locale.US, "%.6f", scalar));
                                spin = 0;
                                step++;
                            }
                        }
                    }
                    break;
                case 6:
                    g.header(6, STEPS, "Drive a loop and come back");
                    g.why("Shows how well the robot keeps track of where it is. Coming back turned a quarter turn also checks the pod offsets and the robot edge sizes.");
                    g.goal("Off by 1 in or less and 2 degrees or less.");
                    if (result == null) {
                        g.doThis("Drive around the field for at least 15 s (turns, both directions).");
                        g.doThis("Then drive back into the SAME corner turned a quarter turn LEFT: left side flat on your alliance wall, back flat on the side wall.");
                        g.value("Driving for", String.format(Locale.US, "%.0f s", loopTimer.seconds()));
                        g.value("Pose now", String.format(Locale.US, "%.1f, %.1f in, %.1f deg", pose.x(), pose.y(), headingDeg));
                        g.keys("cross = back in the corner, triangle = back");
                        // where the robot must be if the odometry is right: square in that corner, edges against the walls
                        Pose corner = Field.cornerPose(pose);
                        boolean quarterTurned = Math.abs(Field.wrapDeg(Math.toDegrees(corner.heading() - start.heading()))) > 45;
                        if (next && loopTimer.seconds() >= MIN_LOOP_S && quarterTurned) {
                            double dx = pose.x() - corner.x(), dy = pose.y() - corner.y();
                            double dh = Field.wrapDeg(Math.toDegrees(pose.heading() - corner.heading()));
                            result = new double[]{Math.hypot(dx, dy), dh};
                            note = g.record("loopErrorInches", result[0]);
                            g.record("loopErrorDegrees", result[1]);
                        } else if (next && !quarterTurned) {
                            note = "come back turned a quarter turn (left side on the alliance wall), not the way it started";
                        } else if (next) {
                            note = "drive a bit longer first";
                        }
                    } else {
                        g.value("Off by", String.format(Locale.US, "%.2f in, %.1f deg", result[0], result[1]));
                        if (result[0] <= OK_DISTANCE_IN && Math.abs(result[1]) <= OK_TURN_DEG) {
                            g.good("PASS: the robot keeps track of where it is.");
                        } else {
                            g.warn("Too far off (limit 1 in, 2 deg). Try once more, edges flat on both walls. Fails again: the Pinpoint tuning (program 5) or the robot edge sizes (C-2) are wrong; tell the programmer.");
                        }
                        g.keys("cross = finish, triangle = put it back in the corner and try the loop again");
                        if (next) step++;
                    }
                    break;
                default:
                    if (!recorded) {
                        recorded = true;
                        g.loadNextOnStop(this);
                    }
                    g.header(0, 0, "Done");
                    g.finished("");
                    break;
            }
            if (!note.isEmpty()) g.warn(note);
            g.update();
        }
        drive.stop();
    }
}
