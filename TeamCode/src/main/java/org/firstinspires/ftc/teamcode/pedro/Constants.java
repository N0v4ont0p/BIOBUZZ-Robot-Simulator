package org.firstinspires.ftc.teamcode.pedro;

import com.pedropathing.algorithm.Foresight;
import com.pedropathing.algorithm.ForesightConfig;
import com.pedropathing.controllers.Controller;
import com.pedropathing.follower.Follower;
import com.pedropathing.math.Matrix;
import com.pedropathing.math.Vector2D;
import com.pedropathing.revhub.drivetrains.Mecanum;
import com.pedropathing.revhub.drivetrains.MecanumConfig;
import com.pedropathing.revhub.localizers.PinpointConfig;
import com.pedropathing.revhub.localizers.PinpointLocalizer;
import com.qualcomm.hardware.gobilda.GoBildaPinpointDriver;
import com.qualcomm.robotcore.hardware.DcMotorSimple;
import com.qualcomm.robotcore.hardware.HardwareMap;

import org.firstinspires.ftc.robotcore.external.navigation.DistanceUnit;
import org.firstinspires.ftc.teamcode.config.DeviceNames;
import org.firstinspires.ftc.teamcode.config.Tuned;

import java.util.OptionalDouble;

// Generated by refract-suite ftc-construct. Values come from team-config.yaml; Double.NaN = untuned.
// Program 5 (Pedro's tuners on the Driver Station) saves these to the robot's results file; the programmer enters them.
public class Constants {
    public static double xPodOffset = Double.NaN;
    public static double yPodOffset = Double.NaN;

    public static double maxAchievableForwardVelocity = Double.NaN;
    public static double maxAchievableStrafeVelocity = Double.NaN;
    public static double naturalForwardDeceleration = Double.NaN;
    public static double naturalStrafeDeceleration = Double.NaN;
    public static double headingBrakingLinearCoefficient = Double.NaN;
    public static double headingBrakingQuadraticCoefficient = Double.NaN;
    public static double headingKP = Double.NaN;
    public static double forwardBrakingLinearCoefficient = Double.NaN;
    public static double forwardBrakingQuadraticCoefficient = Double.NaN;
    public static double strafeBrakingLinearCoefficient = Double.NaN;
    public static double strafeBrakingQuadraticCoefficient = Double.NaN;
    public static double forwardTranslationalPrimaryKP = Double.NaN;
    public static double forwardTranslationalSecondaryKP = Double.NaN;
    public static double strafeTranslationalPrimaryKP = Double.NaN;
    public static double strafeTranslationalSecondaryKP = Double.NaN;
    public static double coastKV = Double.NaN;
    public static double brakeKV = Double.NaN;

    // Pinpoint scale corrections from program 6 (Position Check): pod encoder ticks per mm measured over a
    // 96 in push (NaN = goBILDA's 4-bar figure) and the IMU heading scale measured over 10 turns (NaN = leave
    // the Pinpoint's own calibration).
    public static double podTicksPerMm = Double.NaN;
    public static double imuYawScalar = Double.NaN;

    // Directions are DECODE placeholders (an enum has no NaN): motors as both DECODE robots, pods as 32008.
    // Mecanum Tuner / Pinpoint Tuner replace them.
    public static DcMotorSimple.Direction frontLeftDirection = DcMotorSimple.Direction.REVERSE;
    public static DcMotorSimple.Direction backLeftDirection = DcMotorSimple.Direction.REVERSE;
    public static DcMotorSimple.Direction frontRightDirection = DcMotorSimple.Direction.FORWARD;
    public static DcMotorSimple.Direction backRightDirection = DcMotorSimple.Direction.FORWARD;
    public static GoBildaPinpointDriver.EncoderDirection xPodDirection = GoBildaPinpointDriver.EncoderDirection.FORWARD;
    public static GoBildaPinpointDriver.EncoderDirection yPodDirection = GoBildaPinpointDriver.EncoderDirection.REVERSED;

    // Built on every call from the numbers above, so a setup program that read newer numbers from the robot's
    // results file (LiveResults) gets them without a new build.
    public static MecanumConfig drivetrainConfig() {
        return new MecanumConfig(c -> {
            c.frontLeftName.set(DeviceNames.LEFT_FRONT);
            c.backLeftName.set(DeviceNames.LEFT_BACK);
            c.frontRightName.set(DeviceNames.RIGHT_FRONT);
            c.backRightName.set(DeviceNames.RIGHT_BACK);
            c.frontLeftDirection.set(frontLeftDirection);
            c.backLeftDirection.set(backLeftDirection);
            c.frontRightDirection.set(frontRightDirection);
            c.backRightDirection.set(backRightDirection);
        });
    }

    public static PinpointConfig localizerConfig() {
        return new PinpointConfig(c -> {
            c.name.set(DeviceNames.PINPOINT);
            c.podType.set(GoBildaPinpointDriver.GoBildaOdometryPods.goBILDA_4_BAR_POD);
            if (!Double.isNaN(podTicksPerMm)) {
                c.ticksPerUnit.set(OptionalDouble.of(podTicksPerMm));
                c.encoderResolutionUnit.set(DistanceUnit.MM);
            }
            c.xPodOffset.set(xPodOffset);
            c.yPodOffset.set(yPodOffset);
            c.xPodDirection.set(xPodDirection);
            c.yPodDirection.set(yPodDirection);
            c.globalDistanceUnit.set(DistanceUnit.INCH);
            c.offsetUnits.set(DistanceUnit.INCH);
        });
    }

    public static ForesightConfig foresightConfig() {
        return new ForesightConfig(c -> {
            c.forwardTranslational.set(Controller.piecewise(Controller.proportional(forwardTranslationalSecondaryKP))
                    .put(2.5, Controller.proportional(forwardTranslationalPrimaryKP)));
            c.strafeTranslational.set(Controller.piecewise(Controller.proportional(strafeTranslationalSecondaryKP))
                    .put(2.5, Controller.proportional(strafeTranslationalPrimaryKP)));
            c.coast.set(Controller.proportionalFeedforward(coastKV));
            c.brake.set(Controller.proportionalFeedforward(brakeKV));
            c.headingFeedback.set(Controller.proportional(headingKP));
            c.headingBrakeCoefficients.set(Vector2D.cartesian(headingBrakingLinearCoefficient, headingBrakingQuadraticCoefficient));
            c.linearBrakeCoefficients.set(Matrix.diag(forwardBrakingLinearCoefficient, strafeBrakingLinearCoefficient));
            c.quadraticBrakeCoefficients.set(Matrix.diag(forwardBrakingQuadraticCoefficient, strafeBrakingQuadraticCoefficient));
            c.maxAchievableForwardVelocity.set(maxAchievableForwardVelocity);
            c.maxAchievableStrafeVelocity.set(maxAchievableStrafeVelocity);
            c.naturalForwardDeceleration.set(naturalForwardDeceleration);
            c.naturalStrafeDeceleration.set(naturalStrafeDeceleration);
        });
    }

    public static boolean pinpointTuned() {
        return Tuned.isSet(xPodOffset, yPodOffset);
    }

    public static boolean foresightTuned() {
        return Tuned.isSet(maxAchievableForwardVelocity, maxAchievableStrafeVelocity, naturalForwardDeceleration, naturalStrafeDeceleration, headingBrakingLinearCoefficient, headingBrakingQuadraticCoefficient, headingKP, forwardBrakingLinearCoefficient, forwardBrakingQuadraticCoefficient, strafeBrakingLinearCoefficient, strafeBrakingQuadraticCoefficient, forwardTranslationalPrimaryKP, forwardTranslationalSecondaryKP, strafeTranslationalPrimaryKP, strafeTranslationalSecondaryKP, coastKV, brakeKV);
    }

    // PinpointConfig accepts NaN offsets silently and would send them to the Pinpoint; refuse instead.
    public static PinpointLocalizer localizer(HardwareMap hardwareMap) {
        if (!pinpointTuned()) {
            throw new IllegalStateException("Pinpoint pod offsets not measured: run Pinpoint Tuner first");
        }
        PinpointLocalizer localizer = new PinpointLocalizer(hardwareMap, localizerConfig());
        // CRC needs Pinpoint firmware 3+; a failed check keeps the last good pose instead of a corrupt one.
        GoBildaPinpointDriver pinpoint = pinpoint(hardwareMap);
        if (pinpoint.getDeviceVersion() >= 3) {
            pinpoint.setErrorDetectionType(GoBildaPinpointDriver.ErrorDetectionType.CRC);
        }
        if (!Double.isNaN(imuYawScalar)) pinpoint.setYawScalar(imuYawScalar);
        return localizer;
    }

    // Same device instance the localizer uses (hardwareMap returns one object per name).
    public static GoBildaPinpointDriver pinpoint(HardwareMap hardwareMap) {
        return hardwareMap.get(GoBildaPinpointDriver.class, DeviceNames.PINPOINT);
    }

    public static String pinpointHealth(GoBildaPinpointDriver pinpoint) {
        int firmware = pinpoint.getDeviceVersion();
        return pinpoint.getDeviceStatus() + ", fw " + firmware + (firmware >= 3 ? ", CRC" : ", no CRC (update firmware)");
    }

    public static Mecanum drivetrain(HardwareMap hardwareMap) {
        return new Mecanum(hardwareMap, drivetrainConfig());
    }

    // Foresight rejects NaN when constructed, so autos need the Foresight Tuner run first.
    public static Follower create(HardwareMap hardwareMap) {
        if (!foresightTuned()) {
            throw new IllegalStateException("Foresight not tuned: run Foresight Tuner first");
        }
        return new Follower(localizer(hardwareMap), drivetrain(hardwareMap), new Foresight(foresightConfig()));
    }
}
