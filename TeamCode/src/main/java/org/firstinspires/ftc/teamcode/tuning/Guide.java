// Generated by refract-suite ftc-construct. Shared Driver Station screen for the numbered setup programs
// (1-9, run in order). Every screen shows: which program, which step of how many, what to do, which
// buttons work. Results go to /sdcard/FIRST/biobuzz_results.csv and, at the end, on screen as a RESULTS block:
// a photo of it is all the programmer needs (only the shot tuners' points files still need adb). When a program
// is finished it loads the next one by itself as soon as STOP is pressed (nothing moves until START is pressed on the new one).
public final class Guide {
    public static final String[] PROGRAMS = {
            "1 Check Devices", "2 Motor Directions", "3 Yaw Tuner", "4 Servo Positions", "5 Drive Tuning",
            "6 Position Check", "7 Flywheel Tuner", "8 Front Shot Tuner", "9 Back Shot Tuner"};
    public static final String AFTER_LAST = "BIOBUZZ TeleOp";
    public static final String RESULTS_FILE = LiveResults.FILE;
    private static final int BAR = 12;
    // the SDK walks its listener list while it reports a stop, so the next program loads from a new thread
    private static final long LOAD_DELAY_MS = 500;

    // the SDK keeps listeners only through weak references; this keeps ours alive until it has fired
    private static OpModeManagerNotifier.Notifications pendingLoad;

    private final Telemetry telemetry;
    private final int number;
    private boolean chained = false;
    private final Map<String, String> recorded = new LinkedHashMap<>();
    // values this run changed a lot from what they were (shown under the header)
    private final List<String> bigChanges = new ArrayList<>();
    private final int fromFile;

    public Guide(Telemetry telemetry, int number) {
        this.telemetry = telemetry;
        this.number = number;
        telemetry.setDisplayFormat(Telemetry.DisplayFormat.HTML);
        // before the program builds its parts: they read the numbers once, when made
        fromFile = LiveResults.apply();
    }

    public String nextProgram() {
        return number < PROGRAMS.length ? PROGRAMS[number] : AFTER_LAST;
    }

    public void header(int step, int steps, String title) {
        telemetry.addLine("<big><b><font color='#1565c0'>PROGRAM " + number + " of " + PROGRAMS.length + ": "
                + esc(PROGRAMS[number - 1].substring(2)) + "</font></b></big>");
        if (steps > 0) {
            telemetry.addLine("<b>STEP " + step + " of " + steps + ": " + esc(title) + "</b>");
            telemetry.addLine("<font color='#1565c0'>" + bar(step, steps) + "</font>");
        } else {
            telemetry.addLine("<b>" + esc(title) + "</b>");
        }
        if (fromFile > 0) {
            telemetry.addLine("<font color='#b26a00'>Using " + fromFile + " number" + (fromFile == 1 ? "" : "s")
                    + " from the robot's results file (not in the code yet)</font>");
        }
        if (!LiveResults.problem().isEmpty()) warn(LiveResults.problem());
        for (String c : bigChanges) warn(c);
    }

    // what this step is for
    public void why(String text) {
        telemetry.addLine("<font color='#6a1b9a'><b>WHY:</b> " + esc(text) + "</font>");
    }

    // what a good result looks like
    public void goal(String text) {
        telemetry.addLine("<font color='#2e7d32'><b>GOOD:</b> " + esc(text) + "</font>");
    }

    public void say(String text) {
        telemetry.addLine(esc(text));
    }

    public void doThis(String text) {
        telemetry.addLine("<b>&gt; " + esc(text) + "</b>");
    }

    public void good(String text) {
        telemetry.addLine("<font color='#2e7d32'><b>" + esc(text) + "</b></font>");
    }

    public void warn(String text) {
        telemetry.addLine("<font color='#c62828'><b>" + esc(text) + "</b></font>");
    }

    public void value(String caption, String value) {
        telemetry.addLine(esc(caption) + ": <b>" + esc(value) + "</b>");
    }

    // a line already in the Driver Station's HTML (pictures, result blocks); everything else goes through esc
    public void html(String line) {
        telemetry.addLine(line);
    }

    public static String escape(String s) {
        return esc(s);
    }

    public void keys(String text) {
        telemetry.addLine("<font color='#616161'>Buttons: " + esc(text) + "</font>");
    }

    // shown in INIT when something this program needs is not done yet
    public void notReady(String missing) {
        warn("NOT READY: " + missing);
        say("Do that first (see the setup guide), then INIT this program again.");
    }

    // INIT screen when a device name is not in the Robot Controller configuration; true = do not run
    public boolean missingDevices(LinearOpMode op, String... names) {
        String missing = DeviceNames.missing(op.hardwareMap, names);
        while (!missing.isEmpty() && op.opModeInInit()) {
            header(0, 0, "Before you start");
            notReady("device names " + missing + " (program 1)");
            update();
        }
        return !missing.isEmpty();
    }

    // a flywheel encoder that counts against its power makes the hub's speed control run it to full speed
    public void encoderBackwards(String part) {
        warn("STOP: the " + part + " encoder counts the opposite way to its power. Speed control would run it at full speed.");
        doThis("Press STOP. Check its encoder cable is in the same port number as its motor.");
        doThis("If it is, swap that motor's two power wires (red / black) at its connector.");
        doThis("Then run program 2 again (the direction answer will change) and send the new results file.");
    }

    // files: anything besides the on-screen results that must come off the robot with adb ("" = nothing)
    public void finished(String files) {
        good("PROGRAM " + number + " COMPLETE");
        if (!recorded.isEmpty()) {
            say("Send the programmer a photo of the RESULTS below (scroll down if it goes past the screen).");
            telemetry.addLine("<b>RESULTS P" + number + "</b>");
            for (Map.Entry<String, String> e : recorded.entrySet()) telemetry.addLine("<tt>" + esc(e.getKey()) + " = " + esc(e.getValue()) + "</tt>");
            telemetry.addLine("<b>END P" + number + "</b>");
        }
        if (!files.isEmpty()) say("Also copy " + files + " off the robot with adb (USB cable to the Control Hub works without switching Wi-Fi).");
        doThis("Press STOP. \"" + nextProgram() + "\" loads by itself; read its screen, then press START.");
    }

    public void update() {
        telemetry.update();
    }

    // Call once the program is finished; loads the next program when this one is stopped.
    public void loadNextOnStop(OpMode self) {
        if (chained) return;
        chained = true;
        Activity activity = AppUtil.getInstance().getActivity();
        OpModeManagerImpl manager = activity == null ? null : OpModeManagerImpl.getOpModeManagerOfActivity(activity);
        if (manager == null) return;
        String next = nextProgram();
        pendingLoad = new OpModeManagerNotifier.Notifications() {
            @Override
            public void onOpModePreInit(OpMode opMode) {}

            @Override
            public void onOpModePreStart(OpMode opMode) {}

            @Override
            public void onOpModePostStop(OpMode opMode) {
                if (opMode != self) return;
                OpModeManagerNotifier.Notifications listener = this;
                new Thread(() -> {
                    try {
                        Thread.sleep(LOAD_DELAY_MS);
                    } catch (InterruptedException e) {
                        return;
                    }
                    manager.unregisterListener(listener);
                    pendingLoad = null;
                    manager.initOpMode(next);
                }).start();
            }
        };
        manager.registerListener(pendingLoad);
    }

    // One line per result: program, key, value, time. Returns "" or the error.
    public String record(String key, String value) {
        String before = LiveResults.current(key);
        String error = LiveResults.record(PROGRAMS[number - 1], key, value);
        if (error.isEmpty()) {
            String change = bigChange(key, before, value);
            if (change != null) {
                bigChanges.remove(change);
                bigChanges.add(change);
            }
            recorded.remove(key);
            recorded.put(key, value);
        }
        return error;
    }

    public String record(String key, double value) {
        return record(key, String.format(Locale.US, "%.6g", value));
    }

    // A re-tune that moves a value this much usually means a changed part, a weak battery or a mistake; it is saved
    // anyway and shown. Relative limits (share of the old value) or absolute ones (degrees, inches, servo units).
    // null = no big change (or nothing to compare with).
    public static String bigChange(String key, String before, String now) {
        if (before == null || now == null || before.equals(now)) return null;
        double b, n;
        try {
            b = Double.parseDouble(before);
            n = Double.parseDouble(now);
        } catch (NumberFormatException e) {
            // true / false, FORWARD / REVERSE: any change is worth a look
            return key.matches(".*(Reversed|Direction)") ? key + " changed from " + before + " to " + now + ": a part was rewired or a wrong answer?" : null;
        }
        if (Double.isNaN(b) || Double.isNaN(n)) return null;
        double rel = Double.NaN, abs = Double.NaN;
        if (key.matches(".*(FlywheelF|TopVelocity)|yawTicksPerDeg.*|podTicksPerMm")) rel = 0.05;
        else if (key.matches(".*(FlywheelP|FlywheelI|IdleVelocity)|yawK[psv]|.*KP|.*Coefficient|coastKV|brakeKV")) rel = 0.30;
        else if (key.matches(".*ReadyBand.*|gateTravelS|rampTravelS")) rel = 0.50;
        else if (key.matches("(front|back)(Hood|Gate)(Min|Max|Closed|Open)|ramp(Stowed|Deployed)")) abs = 0.02;
        else if (key.matches(".*Deg|centerTo.*|.*Pivot[XY]|red.*Cell[XY]|[xy]PodOffset")) abs = 1.0;
        else return null;
        double change = Math.abs(n - b);
        boolean big = !Double.isNaN(rel) ? change > rel * Math.abs(b) : change > abs;
        if (!big) return null;
        return String.format(Locale.US, "%s %s -> %s: a big change since the last run (battery? rubbing? a changed part?)", key, before, now);
    }

    private static String bar(int step, int steps) {
        int filled = Math.round(BAR * (float) Math.max(0, step - 1) / steps);
        StringBuilder sb = new StringBuilder("[");
        for (int i = 0; i < BAR; i++) sb.append(i < filled ? '#' : '.');
        return sb.append(']').toString();
    }

    private static String esc(String s) {
        return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;");
    }
}
