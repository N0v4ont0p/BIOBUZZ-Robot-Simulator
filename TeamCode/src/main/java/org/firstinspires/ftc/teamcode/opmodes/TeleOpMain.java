import org.firstinspires.ftc.teamcode.subsystems.Yaw;

// Generated by refract-suite ftc-construct. Always field-centric. The buttons are DECODE's (AASSTEST), PS controllers:
//   gp1 left stick / right stick X  drive / turn          gp1 L1   FIRE MODE on/off: armed = the launchers spin up and
//   gp1 R2 / L2                     intake in / eject               R1 may fire once it is ready (lock, speed, stopped)
//   gp1 R1                          armed: fire both (opens gates, feeds); not armed: intake in
//   gp1 options (DECODE: start)     tap: reseed (robot square in the nearest field corner) and home the turret;
//                                   hold 1.5 s: home the turret only, the Pinpoint is not touched. In INIT it arms
//                                   homing for START (the turret may not move before it)
//   dpad up/down (gp1 or gp2)       distance trim (or manual speed when auto-shooter off)
//   dpad left/right (gp1 or gp2)    angle trim            gp2 L1 / gp2 R1  auto-turret / auto-shooter on/off
//   gp2 triangle / cross hold       manual hood +/- (auto-shooter off)
// BIOBUZZ extra, on a shape button DECODE leaves free:   gp1 triangle   ramp deploy / stow
// Auto-turret = DECODE's lock-on: the turrets track the CELL all the time, fire mode on or off.
// No firing on the move: R1 held waits until the robot has stopped (speed and turn rate under the stopped limits).
// Rumble when both launchers become ready to fire; gamepad light green = ready, red = launchers on, not ready.
// Alliance and pose come from the auto that ran just before. Without one (practice): red, start corner
// (Field.startPose) unless changed in INIT (square = blue, circle = red, options = robot is in the start corner).
// Setup programs never hand their pose to TeleOp.
// Driver Station telemetry only (R704).
@TeleOp(name = "BIOBUZZ TeleOp", group = "19859")
public class TeleOpMain extends LinearOpMode {
    // driver-feel choices carried from DECODE, not robot measurements
    private static final double STICK_DEADBAND = 0.05;
    private static final double TURN_SCALE = 0.9;
    private static final double TRIGGER_THRESHOLD = 0.1;
    private static final double DISTANCE_TRIM_STEP = 2.0;
    private static final double ANGLE_TRIM_STEP = 1.0;
    private static final double MANUAL_VELOCITY_STEP = 20.0;
    private static final double MANUAL_HOOD_STEP = 0.005;
    private static final double MANUAL_DISTANCE = 60.0;
    private static final double FAR_SPLIT = 120.0;

    private double nearDistanceTrim = 0, nearAngleTrim = 0, farDistanceTrim = 0, farAngleTrim = 0;
    private double velocityOffset = 0, hoodOffset = 0;

    @Override
    public void runOpMode() {
        // a setup program run before this one may have put numbers from the results file in place
        LiveResults.restore();
        for (LynxModule hub : hardwareMap.getAll(LynxModule.class)) hub.setBulkCachingMode(LynxModule.BulkCachingMode.AUTO);
        String missing = DeviceNames.missing(hardwareMap, DeviceNames.ALL);
        if (!missing.isEmpty()) {
            while (opModeInInit()) {
                telemetry.addLine("MISSING DEVICES: " + missing + " — fix Configure Robot (setup step D-1)");
                telemetry.update();
            }
            return;
        }
        Drive drive = new Drive(hardwareMap);
        GoBildaPinpointDriver pinpoint = Constants.pinpoint(hardwareMap);
        Intake intake = new Intake(hardwareMap);
        Ramp ramp = new Ramp(hardwareMap);
        Yaw yaw = new Yaw(hardwareMap);
        Launcher front = Launcher.front(hardwareMap);
        Launcher back = Launcher.back(hardwareMap);

        // the auto's pose, or the last TeleOp's if it ended minutes ago (restart in a match). The Pinpoint starts over
        // with every OpMode, so a restart mid-field needs it. Anything older is practice: start corner.
        boolean fromAuto = MatchState.pose != null && MatchState.alliance != null
                && (MatchState.teleOpPoseMs == 0 || System.currentTimeMillis() - MatchState.teleOpPoseMs < MatchState.RESUME_MS);
        if (MatchState.alliance == null) MatchState.alliance = MatchState.Alliance.RED;
        boolean restarted = fromAuto && MatchState.teleOpPoseMs != 0;
        Pose startPose = fromAuto ? MatchState.pose : Field.cornerReseedReady() ? Field.startPose(MatchState.alliance) : null;
        MatchState.pose = null;
        MatchState.teleOpPoseMs = 0;
        if (startPose != null) drive.setPose(startPose);
        boolean poseKnown = drive.localized() && startPose != null;
        TurretZero zero = new TurretZero(yaw);
        OptionsGesture options = new OptionsGesture();
        String startNote = "";

        while (opModeInInit()) {
            OptionsGesture.Event optionsEvent = options.update(gamepad1.options);
            boolean tap = optionsEvent == OptionsGesture.Event.TAP, held = optionsEvent == OptionsGesture.Event.HOLD;
            if (!fromAuto) {
                MatchState.Alliance picked = gamepad1.squareWasPressed() ? MatchState.Alliance.BLUE
                        : gamepad1.circleWasPressed() ? MatchState.Alliance.RED : null;
                if (picked != null || tap) {
                    if (picked != null) MatchState.alliance = picked;
                    String why = startProblem(drive);
                    if (why.isEmpty()) {
                        startPose = Field.startPose(MatchState.alliance);
                        drive.setPose(startPose);
                        poseKnown = true;
                    }
                    startNote = why.isEmpty() ? "start position set" : why;
                }
            }
            if ((tap || held) && !zero.arm() && !YawHoming.available()) {
                startNote = (startNote.isEmpty() ? "" : startNote + "; ") + "turret homing is not set up (program 3): zero it by hand, cross";
            }
            zero.init(gamepad1.crossWasPressed());
            drive.update();
            telemetry.addData("Alliance", MatchState.alliance + (fromAuto ? " (from the auto)" : "  square = blue, circle = red"));
            telemetry.addData("Start", fromAuto ? (restarted ? "where the last TeleOp ended (restart)" : "where the auto ended") : poseKnown ? "start corner: back on your alliance wall, right side on the side wall"
                    : "not set: " + startProblem(drive));
            if (!startNote.isEmpty()) telemetry.addData("Start note", startNote);
            telemetry.addLine(zero.status());
            if (options.down()) telemetry.addLine(String.format(java.util.Locale.US, "Options held %.1f / %.1f s: release before = start corner + home, after = home only", options.heldS(), OptionsGesture.HOLD_S));
            if (!drive.localized()) telemetry.addLine("Pinpoint offsets not measured (E-9): robot-centric only, no aim");
            addPose(drive.pose());
            telemetry.addData("Pinpoint", Constants.pinpointHealth(pinpoint));
            telemetry.update();
        }
        if (isStopRequested()) return;
        zero.start();
        if (startPose != null) drive.setPose(startPose);

        boolean armed = false, autoTurret = true, autoShooter = true, wasReady = false;
        int lastLight = -1;
        boolean firing = false, wasFiring = false;
        ElapsedTime gateTimer = new ElapsedTime();
        String note = "";
        double lastFrontDistance = MANUAL_DISTANCE;
        Pose predictedStop = null;
        String stopNote = "";

        while (opModeIsActive()) {
            drive.update();
            Pose pose = drive.pose();
            MatchState.Alliance alliance = MatchState.alliance;

            // options (DECODE's start button). At the press the turret starts homing (if it was set up in program 3), and
            // a tap then reseeds the Pinpoint: the robot is square in a field corner, take the nearest one. A hold of
            // 1.5 s never reseeds: it only homes.
            OptionsGesture.Event optionsEvent = options.update(gamepad1.options);
            if (optionsEvent == OptionsGesture.Event.PRESS && !zero.startHoming()) {
                note = zero.homing() ? "turret is already homing" : "turret homing is not set up (program 3): the tap only reseeds";
            }
            if (optionsEvent == OptionsGesture.Event.TAP) {
                if (!drive.localized()) {
                    note = "reseed needs Pinpoint offsets (E-9)";
                } else if (Field.cornerReseedReady()) {
                    drive.setPose(Field.cornerPose(pose));
                    note = "reseeded in the nearest corner";
                } else {
                    note = "reseed needs robot edge distances (C-2)";
                }
            }

            if (poseKnown) {
                MatchState.pose = pose;
                MatchState.teleOpPoseMs = System.currentTimeMillis();
            }
            double driverHeading = !drive.localized() ? pose.heading()
                    : alliance == MatchState.Alliance.RED ? 0
                    : alliance == MatchState.Alliance.BLUE ? Math.PI : pose.heading();
            double driverTurn = deadband(-gamepad1.right_stick_x);
            boolean fire = gamepad1.right_bumper;

            // no ready mode and no shots while the turret homes; driving and the intake work as usual
            boolean homingNow = zero.homing();
            if (homingNow) {
                armed = false;
                if (gamepad1.leftBumperWasPressed()) note = "fire mode is off while the turret homes";
            } else if (gamepad1.leftBumperWasPressed()) {
                armed = !armed;
            }
            if (gamepad2.leftBumperWasPressed()) autoTurret = !autoTurret;
            if (gamepad2.rightBumperWasPressed()) {
                autoShooter = !autoShooter;
                velocityOffset = 0;
                hoodOffset = 0;
            }
            if (gamepad1.triangleWasPressed() && !ramp.toggle()) note = "ramp positions not set (E-8)";

            boolean far = lastFrontDistance > FAR_SPLIT;
            boolean up = gamepad1.dpadUpWasPressed() | gamepad2.dpadUpWasPressed();
            boolean down = gamepad1.dpadDownWasPressed() | gamepad2.dpadDownWasPressed();
            boolean leftPad = gamepad1.dpadLeftWasPressed() | gamepad2.dpadLeftWasPressed();
            boolean rightPad = gamepad1.dpadRightWasPressed() | gamepad2.dpadRightWasPressed();
            double step = (up ? 1 : 0) - (down ? 1 : 0);
            if (autoShooter) {
                if (far) farDistanceTrim += step * DISTANCE_TRIM_STEP;
                else nearDistanceTrim += step * DISTANCE_TRIM_STEP;
            } else {
                velocityOffset += step * MANUAL_VELOCITY_STEP;
            }
            double turnStep = (leftPad ? 1 : 0) - (rightPad ? 1 : 0);
            if (far) farAngleTrim += turnStep * ANGLE_TRIM_STEP;
            else nearAngleTrim += turnStep * ANGLE_TRIM_STEP;
            // DECODE: held = keeps moving
            boolean hoodUp = gamepad2.triangle, hoodDown = gamepad2.cross;
            if (!autoShooter) {
                if (hoodUp) hoodOffset += MANUAL_HOOD_STEP;
                if (hoodDown) hoodOffset -= MANUAL_HOOD_STEP;
            }

            double currentFrontDeg = Yaw.calibrated() ? yaw.frontDeg() : Double.NaN;
            boolean still = Math.hypot(drive.velocity().vx, drive.velocity().vy) <= AutoRunner.STOPPED_SPEED
                    && Math.abs(Math.toDegrees(drive.velocity().omega)) <= AutoRunner.STOPPED_TURN_DEG;
            // sticks let go while the robot still moves: aim at where it will have stopped (Foresight's braking model),
            // so the turret is already locked when the robot is still. Driving: the real pose.
            boolean sticksOff = deadband(-gamepad1.left_stick_y) == 0 && deadband(gamepad1.left_stick_x) == 0 && driverTurn == 0;
            Pose stopAt = sticksOff && !still ? drive.stopPose() : null;
            if (stopAt != null && predictedStop == null) predictedStop = stopAt;
            if (stopAt == null && still && predictedStop != null) {
                stopNote = String.format(java.util.Locale.US, "last stop: predicted %.1f in, %.1f deg off", Math.hypot(pose.x() - predictedStop.x(), pose.y() - predictedStop.y()),
                        Math.abs(Field.wrapDeg(Math.toDegrees(pose.heading() - predictedStop.heading()))));
                predictedStop = null;
            }
            if (!sticksOff) predictedStop = null;
            AutoAim.Solution aim = !drive.localized() ? AutoAim.invalid("Pinpoint offsets not measured (E-9)")
                    : AutoAim.solve(stopAt != null ? stopAt : pose, stopAt != null ? Velocity.zero() : drive.velocity(), alliance, currentFrontDeg,
                    far ? farDistanceTrim : nearDistanceTrim, far ? farAngleTrim : nearAngleTrim);
            if (aim.valid) lastFrontDistance = aim.frontDistance;

            double turn = driverTurn * TURN_SCALE;
            drive.driveFieldCentric(deadband(-gamepad1.left_stick_y), deadband(gamepad1.left_stick_x), turn, driverHeading);

            // DECODE lock-on: the turret follows the CELL whenever auto-turret is on, launchers on or not
            boolean aiming = autoTurret && aim.valid && zero.done();
            if (zero.homing()) zero.update();
            else if (aiming) yaw.track(aim.commandFrontDeg, aim.rateFeedforwardDeg);
            else if (zero.done()) yaw.track(0, 0);
            else yaw.stop();

            double feedPower = Double.NaN;
            if (armed) {
                double dFront = aiming ? aim.frontDistance : MANUAL_DISTANCE + (far ? farDistanceTrim : nearDistanceTrim);
                double dBack = aiming ? aim.backDistance : dFront;
                front.aim(dFront, velocityOffset, hoodOffset);
                back.aim(dBack, velocityOffset, hoodOffset);
                feedPower = Math.min(front.feedPower(dFront), back.feedPower(dBack));
            } else {
                front.idle();
                back.idle();
            }

            // both called every loop: each keeps its own "at speed since" timer
            boolean frontSteady = front.steady(), backSteady = back.steady();
            // no shots on the move: it waits until the robot has stopped (the turret keeps aiming meanwhile)
            boolean waitForStop = !still;
            boolean readyToFire = (!autoTurret || (aim.locked && zero.done())) && frontSteady && backSteady && !waitForStop;
            boolean collecting = gamepad1.right_trigger > TRIGGER_THRESHOLD;
            if (collecting) armed = false;
            // gates open once ready and stay open while fire is held; the feed still pauses while a
            // flywheel recovers. Closed otherwise, so collected elements wait off the flywheels.
            firing = fire && armed && (firing || readyToFire);
            if (firing && !wasFiring) gateTimer.reset();
            wasFiring = firing;
            boolean gatesSet = front.setGate(firing) & back.setGate(firing);
            boolean gatesOpen = firing && gatesSet && gateTimer.seconds() >= Tuned.gateTravelS;
            if (fire && armed && (!gatesSet || Double.isNaN(Tuned.gateTravelS))) note = "gate positions/travel not set (E-8)";
            if (collecting) {
                intake.in();
            } else if (gamepad1.left_trigger > TRIGGER_THRESHOLD) {
                intake.eject(gamepad1.left_trigger);
            } else if (fire && armed) {
                if (!gatesOpen || !readyToFire || !intake.feed(feedPower)) intake.stop();
            } else if (fire) {
                // DECODE: R1 with the launchers off collects
                intake.in();
            } else {
                intake.stop();
            }

            boolean showReady = armed && readyToFire;
            if (showReady && !wasReady) {
                gamepad1.rumble(200);
                gamepad2.rumble(200);
            }
            wasReady = showReady;
            if (zero.finishedJustNow()) {
                gamepad1.rumble(100);
                gamepad2.rumble(100);
            }
            // blue = homing, red = armed but not ready, green = ready to fire
            int light = zero.homing() ? 3 : showReady ? 2 : armed ? 1 : 0;
            if (light != lastLight) {
                double red = light == 1 ? 1 : 0, green = light == 2 ? 1 : 0, blue = light == 3 ? 1 : 0;
                gamepad1.setLedColor(red, green, blue, Gamepad.LED_DURATION_CONTINUOUS);
                gamepad2.setLedColor(red, green, blue, Gamepad.LED_DURATION_CONTINUOUS);
                lastLight = light;
            }

            telemetry.addData("Alliance", alliance == null ? "NONE (robot-centric)" : alliance);
            addPose(pose);
            telemetry.addData("Pinpoint", Constants.pinpointHealth(pinpoint));
            telemetry.addData("Battery", "%.1f V", yaw.voltage());
            telemetry.addData("Fire mode (L1)", !armed ? "off: R1 collects"
                    : readyToFire ? "ARMED, READY TO FIRE" : "ARMED, getting ready (aim, speed, robot stopped)");
            telemetry.addData("Auto turret / shooter", (autoTurret ? "on" : "OFF") + " / " + (autoShooter ? "on" : "OFF"));
            if (aim.valid) {
                telemetry.addData("CELL", "%.1f, %.1f", aim.cellX, aim.cellY);
                telemetry.addData("Distance F/B", "%.1f / %.1f in", aim.frontDistance, aim.backDistance);
                telemetry.addData("Yaw cmd / now", "%.1f / %.1f deg", aim.commandFrontDeg, currentFrontDeg);
                telemetry.addData("Residual F/B", "%.1f / %.1f deg", aim.frontErrorDeg, aim.backErrorDeg);
                telemetry.addData("Locked", aim.locked);
            } else {
                telemetry.addData("Aim", aim.problem);
            }
            if (!stopNote.isEmpty()) telemetry.addLine(stopNote);
            // the numbers the stopped check compares, so the limits can be judged on the real robot (AutoRunner.STOPPED_*)
            if (fire && waitForStop) telemetry.addLine(String.format(java.util.Locale.US,
                    "Stop to fire: no shots on the move, let go of the sticks (speed %.1f / %.1f in/s, turn %.1f / %.1f deg/s)",
                    Math.hypot(drive.velocity().vx, drive.velocity().vy), AutoRunner.STOPPED_SPEED,
                    Math.abs(Math.toDegrees(drive.velocity().omega)), AutoRunner.STOPPED_TURN_DEG));
            if (!Yaw.tuned()) telemetry.addLine("Yaw not tuned (G-1 Yaw Tuner): turret unpowered");
            if (zero.showStatus()) telemetry.addLine(zero.status());
            if (options.down()) telemetry.addLine(String.format(java.util.Locale.US, "Options held %.1f / %.1f s", options.heldS(), OptionsGesture.HOLD_S));
            telemetry.addData("Flywheel F", "%.0f / %.0f %s", front.velocity(), front.target(), front.ready() ? "READY" : "");
            telemetry.addData("Flywheel B", "%.0f / %.0f %s", back.velocity(), back.target(), back.ready() ? "READY" : "");
            if (!front.tableSet() || !back.tableSet()) telemetry.addLine("Shot table/PIDF not set (G-3, G-5): launchers stay off");
            telemetry.addData("Trim near", "%.0f in, %.0f deg", nearDistanceTrim, nearAngleTrim);
            telemetry.addData("Trim far", "%.0f in, %.0f deg", farDistanceTrim, farAngleTrim);
            if (!autoShooter) telemetry.addData("Manual offsets", "%.0f t/s, %.3f hood", velocityOffset, hoodOffset);
            telemetry.addData("Ramp", ramp.deployed() ? "DEPLOYED" : "stowed");
            if (!note.isEmpty()) telemetry.addData("Note", note);
            telemetry.update();
        }
        intake.stop();
        front.stop();
        back.stop();
        zero.stop();
        yaw.stop();
        drive.stop();
    }

    // empty when the start position can be set; otherwise what is missing
    static String startProblem(Drive drive) {
        if (MatchState.alliance == null) return "pick the alliance first";
        if (!drive.localized()) return "Pinpoint offsets not measured (E-9)";
        if (!Field.cornerReseedReady()) return "robot edge distances not set (C-2)";
        return "";
    }

    private double deadband(double v) {
        return Math.abs(v) < STICK_DEADBAND ? 0 : v;
    }

    private void addPose(Pose p) {
        telemetry.addData("Pose", "%.1f, %.1f, %.1f deg", p.x(), p.y(), Math.toDegrees(p.heading()));
    }
}
