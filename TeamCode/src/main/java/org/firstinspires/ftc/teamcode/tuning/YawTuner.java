    // ---------- part B: automatic ----------

    // starts from forward (part A ends there); the direction is not known yet, so no moveTo here
    private void signStep(double deg) {
        yaw.setRawPower(SIGN_POWER);
        if (timer.seconds() * 1000 < SIGN_MS) return;
        yaw.setRawPower(0);
        double moved = deg - signStartDeg;
        if (Math.abs(moved) < 0.5) {
            fail("the turret did not move at 10% power: check the gears and cables");
            return;
        }
        sign = moved > 0 ? 1 : -1;
        toStep(Step.KS);
    }

    private void ksStep(double dt, double deg) {
        if (run >= 2) {
            ks = average(ksSamples);
            toStep(Step.KV);
            return;
        }
        double dir = run == 0 ? 1 : -1;
        // past the start the other way, then back onto it: the motor's gear play is closed in the ramp direction,
        // so the ramp has to move the turret itself, not just the motor through the play
        if (phase == 0) {
            if (!moveTo(-dir * KS_TAKEUP_DEG, deg)) return;
            phase = 1;
            moveTimer.reset();
            return;
        }
        if (phase == 1) {
            if (!moveTo(0, deg)) return;
            if (timer.seconds() < REST_S) return;
            phase = 2;
            rampPower = 0;
            rampStartDeg = deg;
            return;
        }
        rampPower += KS_RAMP_PER_S * dt;
        drive(dir * rampPower);
        if (Math.abs(deg - rampStartDeg) >= KS_MOVED_DEG || rampPower > KS_MAX_POWER) {
            yaw.setRawPower(0);
            if (rampPower > KS_MAX_POWER) {
                fail("the turret needed more than 60% power to start moving: check for binding");
                return;
            }
            ksSamples.add(rampPower);
            run++;
            phase = 0;
            moveTimer.reset();
            timer.reset();
        }
    }

    // Each run starts near one end and drives across, so it reaches a steady speed before it must stop.
    // loopS: when this loop read the encoder, so the samples are timed by the loop clock.
    private void kvStep(double deg, double loopS) {
        if (run >= KV_POWERS.length * 2) {
            if (kvData.size() < 2) {
                fail("fewer than 2 of the 8 speed runs reached a steady speed: check for binding or a loose gear, then tell the programmer");
                return;
            }
            kv = slopeThroughOrigin(kvData);
            Collections.sort(reactionSamples);
            reactionS = reactionSamples.get(reactionSamples.size() / 2);
            kp = 1.0 / (4.0 * reactionS);
            toStep(Step.KP);
            return;
        }
        double dir = run % 2 == 0 ? 1 : -1;
        double power = KV_POWERS[run / 2];
        if (phase == 0) {
            double startDeg = dir > 0 ? Tuned.yawMinDeg + START_INSIDE_DEG : Tuned.yawMaxDeg - START_INSIDE_DEG;
            if (!moveTo(startDeg, deg)) return;
            if (timer.seconds() < REST_S) return;
            phase = 1;
            runSamples.clear();
            timer.reset();
            return;
        }
        if (phase == 1) {
            drive(dir * power);
            runSamples.add(new double[]{loopS, deg});
            double end = dir > 0 ? Tuned.yawMaxDeg : Tuned.yawMinDeg;
            double room = dir * (end - deg);
            if (room <= Math.abs(rate) * COAST_S + COAST_EXTRA_DEG || timer.seconds() > RUN_MAX_S) {
                yaw.setRawPower(0);
                recordRun(power);
                run++;
                phase = 0;
                moveTimer.reset();
                timer.reset();
            }
        }
    }

    // Samples are {loop time s, angle deg}. Steady speed = angle turned over the last STEADY_WINDOW_S, if its two
    // halves agree within STEADY_SPREAD plus 2 encoder ticks (each reading can be a tick off; over a whole window
    // that hardly matters). Reaction time = how far the turn lags behind that steady speed since power went on:
    // for this kind of motion that is the time it takes to reach 63% of the speed.
    private void recordRun(double power) {
        if (runSamples.size() < 3) return;
        double[] first = runSamples.get(0), last = runSamples.get(runSamples.size() - 1);
        double[] from = null, mid = null;
        for (double[] s : runSamples) {
            if (from == null && s[0] >= last[0] - STEADY_WINDOW_S) from = s;
            if (mid == null && s[0] >= last[0] - STEADY_WINDOW_S / 2) mid = s;
        }
        boolean full = from != first && from[0] < mid[0] && mid[0] < last[0];
        double steady = full ? Math.abs(last[1] - from[1]) / (last[0] - from[0]) : 0;
        double firstHalf = full ? Math.abs(mid[1] - from[1]) / (mid[0] - from[0]) : 0;
        double secondHalf = full ? Math.abs(last[1] - mid[1]) / (last[0] - mid[0]) : 0;
        double rounding = 2 / Math.abs(Tuned.yawTicksPerDegFront) / (STEADY_WINDOW_S / 2);
        if (steady < 5 || Math.abs(secondHalf - firstHalf) > STEADY_SPREAD * steady + rounding) {
            note = String.format(Locale.US, "%.0f%% power: no steady speed before the stop, skipped", power * 100);
            return;
        }
        kvData.add(new double[]{steady, Math.max(0, power - ks)});
        // never shorter than one loop: that is as fine as it can be measured (and kP = 1 / (4 x it) stays finite)
        double loopS = (last[0] - first[0]) / (runSamples.size() - 1);
        reactionSamples.add(Math.max(loopS, last[0] - first[0] - Math.abs(last[1] - first[1]) / steady));
    }

    // ---------- part C: automatic kP search ----------

    private void kpStep(double deg) {
        Tuned.yawPowerSign = sign;
        Tuned.yawKs = ks;
        Tuned.yawKv = kv;
        Tuned.yawTuningVoltage = voltCount > 0 ? voltSum / voltCount : yaw.voltage();
        Tuned.yawKp = kp;
        double target = STEP_TARGETS[stepIndex];
        if (phase == 0) {
            if (!moveTo(0, deg)) return;
            yaw.stop();
            stepFrom = Double.isNaN(deg) ? 0 : deg;
            worstOvershoot = 0;
            settleSum = 0;
            stepTimedOut = false;
            enteredBandS = -1;
            phase = 1;
            timer.reset();
            return;
        }
        yaw.track(target, 0);
        double past = (deg - target) * Math.signum(target - stepFrom);
        worstOvershoot = Math.max(worstOvershoot, past);
        boolean inBand = Math.abs(deg - target) <= SETTLE_BAND_DEG;
        if (inBand && enteredBandS < 0) enteredBandS = timer.seconds();
        if (!inBand) enteredBandS = -1;
        boolean settled = enteredBandS >= 0 && timer.seconds() - enteredBandS >= SETTLE_HOLD_S;
        double stepTimeout = Math.max(STEP_TIMEOUT_S, 15 * reactionS);
        boolean timedOut = timer.seconds() > stepTimeout;
        if (!settled && !timedOut) return;

        if (timedOut) stepTimedOut = true;
        settleSum += settled ? enteredBandS : stepTimeout;
        stepIndex++;
        if (stepIndex < STEP_TARGETS.length) {
            stepFrom = target;
            timer.reset();
            enteredBandS = -1;
            return;
        }
        // one full set of 4 steps done: judge this kP
        stepIndex = 0;
        phase = 0;
        moveTimer.reset();
        kpTries++;
        double avgSettle = settleSum / STEP_TARGETS.length;
        // only going past the target fails; slow (timed out) with no overshoot just means kP can go up
        boolean pass = worstOvershoot <= OVERSHOOT_LIMIT_DEG;
        note = String.format(Locale.US, "try %d: kP %.2f -> went past by %.1f deg, settled in %.2f s %s",
                kpTries, kp, worstOvershoot, avgSettle, !pass ? "(too much)" : stepTimedOut ? "(slow)" : "(good)");
        if (pass) {
            lastPassKp = kp;
            lastPassSettle = avgSettle;
            lastPassOvershoot = worstOvershoot;
            if (everFailed || kpTries >= KP_MAX_TRIES) {
                finish();
            } else {
                kp *= KP_UP;
            }
        } else {
            everFailed = true;
            if (!Double.isNaN(lastPassKp)) {
                kp = lastPassKp;
                finish();
            } else if (kpTries >= KP_MAX_TRIES) {
                fail("could not stop without going past the target: tell the programmer");
            } else {
                kp *= KP_DOWN;
            }
        }
    }

    private void finish() {
        Tuned.yawKp = kp;
        yaw.stop();
        note = write();
        toStep(Step.READY_HOME);
    }

    // ---------- part D: turret homing ----------

    private int homeDir(int side) {
        return side == 0 ? 1 : -1;
    }

    // where part A found the stop by hand (the soft limit is LIMIT_MARGIN_DEG inside it)
    private double handStop(int side) {
        return side == 0 ? Tuned.yawMaxDeg + LIMIT_MARGIN_DEG : Tuned.yawMinDeg - LIMIT_MARGIN_DEG;
    }

    private void homeTo(Home next) {
        home = next;
        moveTimer.reset();
        timer.reset();
    }

    private double maxRate() {
        return (1 - ks) / Math.max(1e-9, kv);
    }

    private void homeStep(double deg) {
        switch (home) {
            case SIDE_POS: {
                int d = homeDir(homeSide);
                if (!moveTo(handStop(homeSide) - d * SIDE_START_INSIDE_DEG, deg)) return;
                if (timer.seconds() < REST_S) return;
                touch = StopTouch.creepFromInside(yaw, d, StopTouch.CREEP_DEG_S, 2 * SIDE_START_INSIDE_DEG + 20);
                home = Home.SIDE_TOUCH;
                break;
            }
            case SIDE_TOUCH: {
                touch.update();
                homeStatus = String.format(Locale.US, "%s stop: touch %d of %d", homeSide == 0 ? "Left" : "Right", homeSamples.get(homeSide).size() + 1, HOME_REPS);
                if (!touch.finished()) return;
                int d = homeDir(homeSide);
                if (touch.failed()) {
                    homeSideNote[homeSide] = touch.why();
                    nextHomeSide();
                    return;
                }
                List<Double> samples = homeSamples.get(homeSide);
                samples.add(touch.preciseDeg());
                if (samples.size() < HOME_REPS) {
                    touch = StopTouch.backoffThenCreep(yaw, d, touch.preciseDeg(), HOME_BACKOFF_DEG, StopTouch.CREEP_DEG_S, 2 * HOME_BACKOFF_DEG + 20);
                } else {
                    nextHomeSide();
                }
                break;
            }
            case LADDER_POS: {
                int d = homeDir(ladderSide);
                if (!moveTo(homeMean[ladderSide] - d * LADDER_START_INSIDE_DEG, deg)) return;
                if (timer.seconds() < REST_S) return;
                touch = StopTouch.fastThenCreep(yaw, d, ladder[ladderIdx], StopTouch.CREEP_DEG_S, Double.NaN, 2 * LADDER_START_INSIDE_DEG + 30);
                home = Home.LADDER_HIT;
                break;
            }
            case LADDER_HIT: {
                touch.update();
                homeStatus = String.format(Locale.US, "Fast hit at %.0f deg/s", ladder[ladderIdx]);
                if (!touch.finished()) return;
                boolean ok = !touch.failed() && Math.abs(touch.roughDeg() - touch.preciseDeg()) <= HOME_ROUGH_AGREE_DEG
                        && Math.abs(touch.preciseDeg() - homeMean[ladderSide]) <= HOME_SPREAD_MAX_DEG + 0.3;
                if (ok) {
                    vFast = ladder[ladderIdx];
                    ladderIdx++;
                    if (ladderIdx < ladder.length) {
                        homeTo(Home.LADDER_POS);
                        return;
                    }
                }
                startCrossOrFinish();
                break;
            }
            case CROSS_POS: {
                // from just inside the left stop, so the crossing has its whole length
                if (!moveTo(homeMean[0] - SIDE_START_INSIDE_DEG * 0.6, deg)) return;
                if (timer.seconds() < REST_S) return;
                crossMin = Double.POSITIVE_INFINITY;
                home = Home.CROSS_RUN;
                break;
            }
            case CROSS_RUN: {
                homeStatus = String.format(Locale.US, "Crossing at %.0f deg/s", crossSpeeds[crossIdx]);
                double target = homeMean[1] + CROSS_SHORT_DEG;
                crossMin = Math.min(crossMin, deg);
                if (deg <= homeMean[1] + 1.0) {
                    // too close to the stop: this speed is too fast
                    yaw.setRawPower(0);
                    nextCross(false);
                    return;
                }
                if (deg <= target + CROSS_DONE_DEG) {
                    yaw.setRawPower(0);
                    home = Home.CROSS_COAST;
                    timer.reset();
                    return;
                }
                StopTouch.driveRate(yaw, StopTouch.crossRate(deg, target, homeMean[1], -1, crossSpeeds[crossIdx]));
                break;
            }
            case CROSS_COAST: {
                crossMin = Math.min(crossMin, deg);
                yaw.setRawPower(0);
                if (timer.seconds() < CROSS_COAST_S) return;
                double target = homeMean[1] + CROSS_SHORT_DEG;
                boolean ok = target - crossMin <= CROSS_OVERSHOOT_DEG && crossMin > homeMean[1] + 1.0;
                nextCross(ok);
                break;
            }
            default:
                break;
        }
    }

    private void nextHomeSide() {
        List<Double> samples = homeSamples.get(homeSide);
        if (samples.size() == HOME_REPS) {
            double min = Collections.min(samples), max = Collections.max(samples);
            homeMean[homeSide] = average(samples);
            homeSpread[homeSide] = max - min;
            homePassed[homeSide] = max - min <= HOME_SPREAD_MAX_DEG;
            if (!homePassed[homeSide]) homeSideNote[homeSide] = String.format(Locale.US, "the five touches differ by %.2f deg (limit %.1f): not a firm stop", max - min, HOME_SPREAD_MAX_DEG);
        }
        if (homeSide == 0) {
            homeSide = 1;
            homeTo(Home.SIDE_POS);
            return;
        }
        // the encoder's tick is the floor of the accuracy
        if (1 / Math.abs(Tuned.yawTicksPerDegFront) > HOME_TICK_MAX_DEG) {
            homePassed[0] = homePassed[1] = false;
            homeSideNote[0] = homeSideNote[1] = String.format(Locale.US, "one encoder tick is %.2f deg, more than the %.2f deg homing needs", 1 / Math.abs(Tuned.yawTicksPerDegFront), HOME_TICK_MAX_DEG);
        }
        if (!homePassed[0] && !homePassed[1]) {
            finishHome();
            return;
        }
        ladderSide = !homePassed[0] ? 1 : !homePassed[1] ? 0 : (homeSpread[0] <= homeSpread[1] ? 0 : 1);
        List<Double> speeds = new ArrayList<>();
        for (double v : LADDER_DEG_S) if (v <= MAX_RATE_SHARE * maxRate()) speeds.add(v);
        ladder = new double[speeds.size()];
        for (int i = 0; i < ladder.length; i++) ladder[i] = speeds.get(i);
        ladderIdx = 0;
        vFast = Double.NaN;
        if (ladder.length == 0) {
            startCrossOrFinish();
        } else {
            homeTo(Home.LADDER_POS);
        }
    }

    private void startCrossOrFinish() {
        if (Double.isNaN(vFast)) vFast = StopTouch.CREEP_DEG_S;
        if (!(homePassed[0] && homePassed[1])) {
            vCross = StopTouch.CREEP_DEG_S;
            finishHome();
            return;
        }
        List<Double> speeds = new ArrayList<>();
        for (double v : CROSS_DEG_S) if (v <= 0.7 * maxRate()) speeds.add(v);
        if (speeds.isEmpty()) speeds.add(CROSS_DEG_S[CROSS_DEG_S.length - 1]);
        crossSpeeds = new double[speeds.size()];
        for (int i = 0; i < crossSpeeds.length; i++) crossSpeeds[i] = speeds.get(i);
        crossIdx = 0;
        vCross = Double.NaN;
        homeTo(Home.CROSS_POS);
    }

    private void nextCross(boolean ok) {
        if (ok) {
            vCross = crossSpeeds[crossIdx];
            finishHome();
            return;
        }
        crossIdx++;
        if (crossIdx >= crossSpeeds.length) {
            vCross = crossSpeeds[crossSpeeds.length - 1];
            finishHome();
            return;
        }
        homeTo(Home.CROSS_POS);
    }

    // results, the times for the real travel, the file; then the end of the program
    private void finishHome() {
        yaw.setRawPower(0);
        boolean any = !homeSkipped && (homePassed[0] || homePassed[1]);
        String err = "";
        if (any) {
            double span = homePassed[0] && homePassed[1] ? homeMean[0] - homeMean[1] : (Tuned.yawMaxDeg - Tuned.yawMinDeg) + 20;
            boolean two = homePassed[0] && homePassed[1];
            double firstTyp = span / 2 / vFast + HOME_TAIL_S, firstWorst = span / vFast + HOME_TAIL_S;
            double second = YawHoming.secondSideS(span, vCross);
            // with both stops measured every homing checks the second stop too (a snag cannot pass as a stop)
            double typical = two ? firstTyp + second : firstTyp;
            double worst = two ? firstWorst + second : firstWorst;
            double spread = 0;
            for (int i = 0; i < 2; i++) if (homePassed[i]) spread = Math.max(spread, homeSpread[i]);
            err = g.record("yawHomeLeftDeg", homePassed[0] ? fmt(homeMean[0]) : "NaN");
            g.record("yawHomeRightDeg", homePassed[1] ? fmt(homeMean[1]) : "NaN");
            g.record("yawHomeFastDegS", fmt(vFast));
            g.record("yawHomeCreepDegS", fmt(StopTouch.CREEP_DEG_S));
            g.record("yawHomeCrossDegS", fmt(vCross));
            g.record("yawHomeSpreadDeg", fmt(spread));
            g.record("yawHomeTypicalS", fmt(typical));
            g.record("yawHomeWorstS", fmt(worst));
            homeSummary[0] = "HOMING AVAILABLE (" + (two ? "both stops" : (homePassed[0] ? "left stop only" : "right stop only")) + ")";
            homeSummary[1] = String.format(Locale.US, "Stops: left %s, right %s (front-turret deg from forward)", homePassed[0] ? String.format(Locale.US, "%.2f", homeMean[0]) : "not usable",
                    homePassed[1] ? String.format(Locale.US, "%.2f", homeMean[1]) : "not usable");
            homeSummary[2] = String.format(Locale.US, "Slow touches agreed within %.2f deg (limit %.1f)", spread, HOME_SPREAD_MAX_DEG);
            homeSummary[3] = String.format(Locale.US, "Fast hit %.0f deg/s, slow touch %.0f deg/s, crossing %.0f deg/s", vFast, StopTouch.CREEP_DEG_S, vCross);
            homeSummary[4] = String.format(Locale.US, "Homing time: about %.1f s typical, %.1f s worst case", typical, worst);
            homeSummary[5] = two ? "" : "Only one stop: a homing on one stop is not cross-checked (a snag would pass as the stop). Fix the other stop and run part D again.";
        } else {
            for (String key : new String[]{"yawHomeLeftDeg", "yawHomeRightDeg", "yawHomeFastDegS", "yawHomeCreepDegS", "yawHomeCrossDegS"}) {
                String e = g.record(key, "NaN");
                if (err.isEmpty()) err = e;
            }
            if (!homeSkipped) {
                homeSummary[0] = "HOMING NOT AVAILABLE: no stop repeated well enough.";
                homeSummary[1] = "Left: " + (homeSideNote[0].isEmpty() ? "not tested" : homeSideNote[0]);
                homeSummary[2] = "Right: " + (homeSideNote[1].isEmpty() ? "not tested" : homeSideNote[1]);
                homeSummary[3] = "By hand stays the way to zero: both turrets straight forward, cross in INIT.";
            }
        }
        if (!err.isEmpty()) note = err;
        step = Step.DONE;
        g.loadNextOnStop(this);
    }

    // ---------- helpers ----------

    // Slow move to an angle at RETURN_POWER; true once there.
    private boolean moveTo(double target, double deg) {
        double err = target - deg;
        if (Math.abs(err) <= RETURN_TOLERANCE_DEG) {
            yaw.setRawPower(0);
            return true;
        }
        if (moveTimer.seconds() > MOVE_TIMEOUT_S) {
            fail("could not move back to the start angle: check for binding");
            return false;
        }
        double floor = ks > 0 ? Math.max(RETURN_MIN_POWER, ks + RETURN_ABOVE_KS) : RETURN_MIN_POWER;
        double magnitude = Math.max(floor, RETURN_POWER * Math.min(1, Math.abs(err) / RETURN_SLOWDOWN_DEG));
        drive(Math.signum(err) * magnitude);
        timer.reset();
        return false;
    }

    private void drive(double power) {
        yaw.setRawPower(sign * power);
    }

    private void toStep(Step next) {
        step = next;
        phase = 0;
        run = 0;
        timer.reset();
        moveTimer.reset();
        note = "";
    }

    private void fail(String why) {
        yaw.setRawPower(0);
        error = why;
        step = Step.ERROR;
    }

    private boolean scaleKnown() {
        return !Double.isNaN(Tuned.yawTicksPerDegFront) && step.ordinal() > Step.FRONT_RIGHT.ordinal();
    }

    private static double slopeThroughOrigin(List<double[]> data) {
        double sxy = 0, sxx = 0;
        for (double[] p : data) {
            sxy += p[0] * p[1];
            sxx += p[0] * p[0];
        }
        return sxx <= 0 ? 0 : sxy / sxx;
    }

    private static double average(List<Double> data) {
        double sum = 0;
        for (double v : data) sum += v;
        return data.isEmpty() ? 0 : sum / data.size();
    }

    private String write() {
        String[][] rows = {
                {"yawTicksPerDegFront", fmt(Tuned.yawTicksPerDegFront)}, {"yawTicksPerDegBack", fmt(Tuned.yawTicksPerDegBack)},
                {"yawMinDeg", fmt(Tuned.yawMinDeg)}, {"yawMaxDeg", fmt(Tuned.yawMaxDeg)}, {"yawPowerSign", fmt(sign)},
                {"yawKs", fmt(ks)}, {"yawKv", fmt(kv)}, {"yawTuningVoltage", fmt(Tuned.yawTuningVoltage)}, {"yawKp", fmt(kp)},
                {"yawReactionTimeS", fmt(reactionS)}, {"yawSettleS", fmt(lastPassSettle)}, {"yawPastTargetDeg", fmt(lastPassOvershoot)},
                {"yawSpeedPoints", String.valueOf(kvData.size())}, {"yawPlayDeg", fmt(play)}};
        String error = "";
        double indexDeg = indexDeg();
        if (!Double.isNaN(indexDeg)) error = g.record("yawIndexDeg", fmt(indexDeg));
        for (String[] r : rows) {
            String e = g.record(r[0], r[1]);
            if (error.isEmpty()) error = e;
        }
        return error;
    }

    // where the index switch turns on while turning LEFT, from true forward (midway between straight left and
    // right); NaN without the switch or before it was passed that way
    private double indexDeg() {
        if (!yaw.indexPresent() || step.ordinal() <= Step.FRONT_RIGHT.ordinal()) return Double.NaN;
        int edge = Tuned.yawTicksPerDegFront > 0 ? indexUpTicks : indexDownTicks;
        if (edge == Integer.MIN_VALUE) return Double.NaN;
        return (edge - (frontLeftTicks + frontRightTicks) / 2.0) / Tuned.yawTicksPerDegFront;
    }

    private static String fmt(double v) {
        return String.format(Locale.US, "%.6g", v);
    }

    private static final int STEPS = 14;

    private void report(double deg) {
        String title;
        int n;
        switch (step) {
            case FRONT_LEFT: n = 1; title = "Front turret straight LEFT"; break;
            case FRONT_RIGHT: n = 2; title = "Front turret straight RIGHT"; break;
            case BACK_LEFT: n = 3; title = "Back turret straight LEFT"; break;
            case BACK_RIGHT: n = 4; title = "Back turret straight RIGHT"; break;
            case STOP_LEFT: n = 5; title = "Left stop"; break;
            case STOP_RIGHT: n = 6; title = "Right stop"; break;
            case CENTER: n = 7; title = "Back to forward"; break;
            case PLAY: n = 8; title = "Gear play (E-6)"; break;
            case READY_B: n = 9; title = "Get ready: automatic part"; break;
            case SIGN: case KS: case KV: n = 10; title = "Automatic: friction and speed"; break;
            case KP: n = 11; title = "Automatic: fastest setting without going past"; break;
            case READY_HOME: n = 12; title = "Get ready: homing test"; break;
            case HOME: n = 13; title = "Automatic: turret homing"; break;
            default: n = 14; title = step == Step.DONE ? "Done" : "Stopped"; break;
        }
        g.header(n, STEPS, title);
        g.why(whyText(step));
        if (!goalText(step).isEmpty()) g.goal(goalText(step));
        switch (step) {
            case PLAY:
                g.say("The yaw motor now holds still.");
                g.doThis("Rock the FRONT turret gently left and right by hand. Read on a degree scale how far it moves freely, end to end.");
                g.doThis("Set that number with dpad up / down, then cross.");
                g.value("Play", String.format(Locale.US, "%.1f deg", play));
                g.keys("dpad up / down = +/- 0.1 deg, cross = save and next, triangle = back");
                break;
            case READY_B:
                g.say("Part A (by hand) is done. Next the turrets move BY THEMSELVES, fast.");
                g.doThis("Clear the area, cables free, hands away. Then press cross.");
                g.keys("cross = start, triangle = back");
                break;
            case SIGN: case KS: case KV:
                g.say("Measuring how hard the turrets are to start and how fast they turn at 4 power levels.");
                g.say("Hands away. To abort: STOP.");
                if (step == Step.KV) g.value("Speed runs done", Math.min(run, KV_POWERS.length * 2) + " of " + KV_POWERS.length * 2);
                break;
            case KP:
                g.say("The turret jumps +30, 0, -30, 0 degrees, each round a bit faster.");
                g.say("It keeps the fastest setting that goes past its target by 1 degree or less (no wobble).");
                g.value("Round", String.valueOf(kpTries + 1));
                break;
            case READY_HOME:
                g.say("Last part. The turrets are driven into their end stops to measure homing: with it the turret finds its own zero"
                        + " after a power-up, with no turning it forward by hand and no extra hardware.");
                g.doThis("Clear the area, cables free, hands away: the turrets touch each stop 5 times slowly, then hit it faster. Then press cross.");
                g.say("Nothing here can hurt a hard stop, but if it sounds wrong press STOP.");
                g.keys("cross = start, triangle = skip (homing stays off)");
                break;
            case HOME:
                g.say("Hands away. To abort: STOP.");
                g.value("Now", homeStatus);
                for (int side = 0; side < 2; side++) {
                    List<Double> samples = homeSamples.get(side);
                    if (!samples.isEmpty()) {
                        StringBuilder sb = new StringBuilder();
                        for (double v : samples) sb.append(String.format(Locale.US, "%.2f  ", v));
                        g.value(side == 0 ? "Left stop angles" : "Right stop angles", sb.toString());
                    }
                }
                if (!Double.isNaN(vFast)) g.value("Fastest safe hit so far", String.format(Locale.US, "%.0f deg/s", vFast));
                break;
            case DONE:
                g.finished("");
                for (String line : homeSummary) {
                    if (line == null || line.isEmpty()) continue;
                    if (line.startsWith("HOMING AVAILABLE")) g.good(line);
                    else if (line.startsWith("HOMING NOT") || line.startsWith("The worst case")) g.warn(line);
                    else g.say(line);
                }
                break;
            case ERROR:
                g.warn("STOPPED: " + error);
                g.doThis("Fix that, then STOP and run this program again from the start.");
                break;
            default:
                g.doThis(partAInstruction(step));
                g.say("Turn by hand, or hold dpad left / right to turn slowly (it may turn the opposite way).");
                if (step.ordinal() <= Step.BACK_RIGHT.ordinal()) {
                    g.say("Can't get it straight left or right? The turret must turn more than 90 degrees each way: check the cable and stops, then tell the programmer.");
                }
                g.keys("cross = save and next" + (step == Step.FRONT_LEFT ? "" : ", triangle = back"));
                break;
        }
        g.value("Yaw", Double.isNaN(deg) ? yaw.ticks() + " ticks" : String.format(Locale.US, "%.1f deg  (%d ticks)", deg, yaw.ticks()));
        if (!Double.isNaN(Tuned.yawTicksPerDegFront) && scaleKnown()) {
            g.value("Scale front / back", String.format(Locale.US, "%.3f / %.3f ticks per deg", Tuned.yawTicksPerDegFront, Tuned.yawTicksPerDegBack));
        }
        if (yaw.indexPresent() && step.ordinal() > Step.FRONT_RIGHT.ordinal()) {
            double at = indexDeg();
            g.value("Index switch", Double.isNaN(at) ? "not passed SLOWLY turning LEFT yet: on the way back from straight right, turn slowly through forward"
                    : String.format(Locale.US, "turns on at %.1f deg turning left", at));
        }
        if (!Double.isNaN(Tuned.yawMinDeg) && step.ordinal() > Step.STOP_RIGHT.ordinal()) {
            g.value("Limits", String.format(Locale.US, "%.0f to %.0f deg", Tuned.yawMinDeg, Tuned.yawMaxDeg));
        }
        if (step.ordinal() > Step.KS.ordinal()) g.value("kS", String.format(Locale.US, "%.4f", ks));
        if (step.ordinal() > Step.KV.ordinal()) {
            g.value("kV / reaction time", String.format(Locale.US, "%.6f / %.3f s", kv, reactionS));
            g.value("kP", String.format(Locale.US, "%.2f", kp));
        }
        if (!note.isEmpty()) g.warn(note);
        g.update();
    }
