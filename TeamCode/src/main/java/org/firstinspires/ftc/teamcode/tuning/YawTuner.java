    // ---------- part A: by hand ----------

    private void partA(boolean cross, boolean triangle) {
        double jog = (gamepad1.dpad_left ? 1 : 0) - (gamepad1.dpad_right ? 1 : 0);
        yaw.setRawPower(jog * JOG_POWER);
        int ticks = yaw.ticks();
        if (triangle && step != Step.FRONT_LEFT) {
            toStep(Step.values()[step.ordinal() - 1]);
            return;
        }
        if (!cross) return;
        switch (step) {
            case FRONT_LEFT:
                frontLeftTicks = ticks;
                toStep(Step.FRONT_RIGHT);
                break;
            case FRONT_RIGHT:
                frontRightTicks = ticks;
                if (Math.abs(frontLeftTicks - frontRightTicks) < 10) {
                    note = "left and right read the same: turn the turret further";
                    return;
                }
                // forward is midway between straight left and right; the INIT zero should be there
                double forwardDeg = (frontLeftTicks + frontRightTicks) / (double) (frontLeftTicks - frontRightTicks) * 90;
                if (Math.abs(forwardDeg) > ZERO_TOLERANCE_DEG) {
                    note = String.format(Locale.US, "left and right are not even around the INIT zero (%.0f deg off): the turrets were not straight"
                            + " forward at INIT. STOP, turn them forward by hand, INIT again (or redo left / right with triangle)", forwardDeg);
                    return;
                }
                Tuned.yawTicksPerDegFront = (frontLeftTicks - frontRightTicks) / 180.0;
                toStep(Step.BACK_LEFT);
                break;
            case BACK_LEFT:
                backLeftTicks = ticks;
                toStep(Step.BACK_RIGHT);
                break;
            case BACK_RIGHT:
                backRightTicks = ticks;
                if (Math.abs(backLeftTicks - backRightTicks) < 10) {
                    note = "left and right read the same: turn the turret further";
                    return;
                }
                Tuned.yawTicksPerDegBack = (backLeftTicks - backRightTicks) / 180.0;
                toStep(Step.STOP_LEFT);
                break;
            case STOP_LEFT:
            case STOP_RIGHT:
                boolean left = step == Step.STOP_LEFT;
                double stopDeg = yaw.frontDeg();
                if ((left ? stopDeg : -stopDeg) < MIN_STOP_DEG) {
                    note = String.format(Locale.US, "this stop is only %.0f deg from forward, but it must be past straight %s (90 deg)."
                            + " Not at the stop yet: turn further, then cross. Really stops there: check the cable and stops, tell the programmer",
                            Math.abs(stopDeg), left ? "left" : "right");
                    return;
                }
                if (left) Tuned.yawMaxDeg = stopDeg - LIMIT_MARGIN_DEG;
                else Tuned.yawMinDeg = stopDeg + LIMIT_MARGIN_DEG;
                toStep(left ? Step.STOP_RIGHT : Step.CENTER);
                break;
            case CENTER:
                if (Math.abs(yaw.frontDeg()) > CENTER_TOLERANCE_DEG) {
                    note = "not pointing forward yet";
                    return;
                }
                toStep(Step.PLAY);
                break;
            default:
                break;
        }
    }

    // E-6: the motor holds still (brakes); the student rocks the front turret by hand and reads its free play
    private void playStep(boolean cross, boolean triangle) {
        yaw.setFloat(false);
        yaw.setRawPower(0);
        if (gamepad1.dpadUpWasPressed()) play += PLAY_STEP_DEG;
        if (gamepad1.dpadDownWasPressed()) play = Math.max(0, play - PLAY_STEP_DEG);
        if (triangle) {
            yaw.setFloat(true);
            toStep(Step.CENTER);
        } else if (cross) {
            Tuned.yawPlayDeg = play;
            toStep(Step.READY_B);
        }
    }

