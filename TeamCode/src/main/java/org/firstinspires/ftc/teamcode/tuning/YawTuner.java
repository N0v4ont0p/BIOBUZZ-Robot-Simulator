    @Override
    public void loop() {
        if (yaw == null) return;
        long now = System.nanoTime();
        double dt = (now - lastNanos) / 1e9;
        if (dt <= 1e-5) return;
        lastNanos = now;
        double deg = scaleKnown() ? yaw.frontDeg() : Double.NaN;
        if (!Double.isNaN(deg)) {
            rate = RATE_ALPHA * (deg - lastDeg) / dt + (1 - RATE_ALPHA) * rate;
            lastDeg = deg;
        }
        if (yaw.indexPresent() && step.ordinal() <= Step.CENTER.ordinal()) {
            int t = yaw.ticks();
            boolean on = yaw.atIndex();
            // direction and speed over the last ~0.1 s (a hand moves less than a count per loop); only a slow pass
            // counts (the speed is known once the scale is; before that every pass counts)
            if (indexLastTicks != Integer.MIN_VALUE && t != indexLastTicks) indexMoveDir = t > indexLastTicks ? 1 : -1;
            indexLastTicks = t;
            if (on && !indexWasOn && indexRefTicks != Integer.MIN_VALUE && indexMoveDir != 0) {
                double degPerS = Double.isNaN(deg) ? 0 : Math.abs((t - indexRefTicks) / Tuned.yawTicksPerDegFront) / Math.max(1e-3, (now - indexRefNs) / 1e9);
                if (degPerS <= Yaw.INDEX_MAX_DEG_S) {
                    if (indexMoveDir > 0) indexUpTicks = t;
                    else indexDownTicks = t;
                }
            }
            indexWasOn = on;
            if (indexRefTicks == Integer.MIN_VALUE || now - indexRefNs >= 100_000_000L) {
                indexRefTicks = t;
                indexRefNs = now;
            }
        }
        boolean cross = gamepad1.crossWasPressed(), triangle = gamepad1.triangleWasPressed();
        if (step.ordinal() >= Step.SIGN.ordinal() && step.ordinal() <= Step.KP.ordinal()) {
            voltSum += yaw.voltage();
            voltCount++;
            if (deg > Tuned.yawMaxDeg + SAFETY_DEG || deg < Tuned.yawMinDeg - SAFETY_DEG) {
                fail("turret went past a stop limit: check the stops in part A, then run again");
            }
        }

        switch (step) {
            case FRONT_LEFT:
            case FRONT_RIGHT:
            case BACK_LEFT:
            case BACK_RIGHT:
            case STOP_LEFT:
            case STOP_RIGHT:
            case CENTER:
                partA(cross, triangle);
                break;
            case PLAY:
                playStep(cross, triangle);
                break;
            case READY_B:
                yaw.setRawPower(0);
                if (cross) {
                    yaw.setFloat(false);
                    signStartDeg = deg;
                    toStep(Step.SIGN);
                }
                if (triangle) toStep(Step.PLAY);
                break;
            case SIGN: signStep(deg); break;
            case KS: ksStep(dt, deg); break;
            case KV: kvStep(deg, now / 1e9); break;
            case KP: kpStep(deg); break;
            case READY_HOME:
                yaw.setRawPower(0);
                if (cross) {
                    toStep(Step.HOME);
                    home = Home.SIDE_POS;
                } else if (triangle) {
                    homeSkipped = true;
                    homeSummary[0] = "Homing skipped: it stays OFF (by hand: both turrets straight forward, cross in INIT).";
                    finishHome();
                }
                break;
            case HOME: homeStep(deg); break;
            default: yaw.setRawPower(0); break;
        }
        report(deg);
    }

