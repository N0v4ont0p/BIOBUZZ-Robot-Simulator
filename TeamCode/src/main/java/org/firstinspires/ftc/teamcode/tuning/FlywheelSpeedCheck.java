package org.firstinspires.ftc.teamcode.tuning;

import com.qualcomm.hardware.lynx.LynxModule;
import com.qualcomm.robotcore.eventloop.opmode.LinearOpMode;
import com.qualcomm.robotcore.eventloop.opmode.TeleOp;
import com.qualcomm.robotcore.hardware.DcMotor;
import com.qualcomm.robotcore.hardware.DcMotorEx;
import com.qualcomm.robotcore.hardware.DcMotorSimple;
import com.qualcomm.robotcore.hardware.Servo;
import com.qualcomm.robotcore.util.ElapsedTime;

import org.firstinspires.ftc.teamcode.config.DeviceNames;
import org.firstinspires.ftc.teamcode.config.Tuned;
import org.firstinspires.ftc.teamcode.opmodes.AutoRunner;
import org.firstinspires.ftc.teamcode.subsystems.Intake;
import org.firstinspires.ftc.teamcode.subsystems.Launcher;

import java.util.Locale;

// Generated by refract-suite ftc-construct. PRACTICE ONLY. Program 7's optional last part, once both shot tables
// exist (programs 8 and 9): checks each flywheel at its real shot speeds, the lowest and the highest in its table.
//   1 hold the lowest and 2 the highest shot speed (nothing loaded): the ready band at each speed
//   3 two recovery shots at each speed (load ONE, R2): steady again within 2 s with that speed's band?
//   4 the idle speed again, against both shot speeds: per idle the slower of the two climbs counts
// The band per speed is saved only when every check passes (both holds settled, each band under 10 % of its speed,
// the 70 % band from program 7 fits between them within 40 %, all four shots steady); if the two bands are within
// 25 % of each other one band is enough and both ends are saved as program 7's band (so nothing changes). A band is
// never narrower than program 7's: a too narrow band would hold
// shots back in TeleOp. Launcher.ready() then uses the band of the target speed, in a straight line between the two.
@TeleOp(name = "7 Flywheel Tuner: shot-speed check", group = "19859 Setup")
public class FlywheelSpeedCheck extends LinearOpMode {
    // test procedure settings, not robot measurements (the same as program 7's)
    // settled = within NEAR_SHARE for NEAR_S (2 s: with 1 s the tail of the spin-up now and then made a band twice too wide)
    private static final double NEAR_SHARE = 0.05, NEAR_S = 2.0, SETTLE_MAX_S = 6.0, MEASURE_S = 2.0;
    private static final double FEED_TEST_POWER = 0.6, WATCH_S = 2.0, OUT_BLIP_S = 0.05, STEADY_PROOF_S = 0.3, ARRIVED_S = 0.2;
    private static final double[] IDLE_FRACTIONS = {0, 0.2, 0.35, 0.5, 0.65};
    private static final double IDLE_CAP = 0.65, IDLE_SETTLE_S = 0.3, IDLE_SETTLE_MAX_S = 3.0, IDLE_UP_MAX_S = 3.0;
    private static final double BAND_MAX_SHARE = 0.10, BAND_DIFFERENT = 0.25, BAND_FIT = 0.40;
    private static final int SHOTS_PER_SPEED = 2;

    private enum Step { HOLD_LOW, HOLD_HIGH, SHOTS, IDLE, RESULT }

    @Override
    public void runOpMode() {
        Guide g = new Guide(telemetry, 7);
        if (g.missingDevices(this, DeviceNames.FRONT_FLYWHEEL, DeviceNames.BACK_FLYWHEEL, DeviceNames.INTAKE, DeviceNames.FRONT_GATE, DeviceNames.BACK_GATE)) return;
        for (LynxModule hub : hardwareMap.getAll(LynxModule.class)) hub.setBulkCachingMode(LynxModule.BulkCachingMode.AUTO);
        String[] sides = {"front", "back"};
        DcMotorEx[] wheels = {motor(DeviceNames.FRONT_FLYWHEEL, Launcher.FRONT_REVERSED), motor(DeviceNames.BACK_FLYWHEEL, Launcher.BACK_REVERSED)};
        Servo[] gates = {hardwareMap.get(Servo.class, DeviceNames.FRONT_GATE), hardwareMap.get(Servo.class, DeviceNames.BACK_GATE)};
        double[][] gate = {{Tuned.frontGateClosed, Tuned.frontGateOpen}, {Tuned.backGateClosed, Tuned.backGateOpen}};
        double[] p = {Tuned.frontFlywheelP, Tuned.backFlywheelP}, f = {Tuned.frontFlywheelF, Tuned.backFlywheelF};
        double[] band70 = {Tuned.frontReadyBand, Tuned.backReadyBand};
        double[][] speeds = new double[2][];
        Intake intake = new Intake(hardwareMap);
        String missing = "";
        for (int k = 0; k < 2; k++) {
            double[][] rows = Launcher.shotTable(sides[k]);
            if (rows.length >= 2) {
                double lo = Double.POSITIVE_INFINITY, hi = 0;
                for (double[] r : rows) {
                    lo = Math.min(lo, r[Launcher.SPEED]);
                    hi = Math.max(hi, r[Launcher.SPEED]);
                }
                speeds[k] = new double[]{lo, hi};
            }
            if (!Tuned.isSet(p[k], f[k], band70[k])) missing += sides[k] + " flywheel tuning (program 7), ";
            if (speeds[k] == null) missing += sides[k] + " shot table (program " + (k == 0 ? 8 : 9) + "), ";
            if (!Tuned.isSet(gate[k][0], gate[k][1])) missing += sides[k] + " gate positions (program 4), ";
        }
        if (!Tuned.isSet(Tuned.gateTravelS)) missing += "gate travel time (program 4), ";
        while (opModeInInit()) {
            g.header(0, 0, "Shot-speed check (optional, after programs 8 and 9)");
            g.why("Program 7 tuned at 70% of top speed; real shots run from the shortest to the longest table speed.");
            if (!missing.isEmpty()) {
                g.notReady(missing.substring(0, missing.length() - 2));
            } else {
                g.say(String.format(Locale.US, "Front: %.0f and %.0f ticks/s. Back: %.0f and %.0f ticks/s.", speeds[0][0], speeds[0][1], speeds[1][0], speeds[1][1]));
                g.doThis("Robot on a box, nothing loaded, hands clear. Press START. You will load ONE element at a time when asked.");
            }
            g.update();
        }
        if (isStopRequested() || !missing.isEmpty()) return;
        for (int k = 0; k < 2; k++) gates[k].setPosition(gate[k][0]);

        int side = 0;
        Step step = Step.HOLD_LOW;
        boolean running = false, finished = false;
        ElapsedTime timer = new ElapsedTime(), shotTimer = new ElapsedTime();
        // per side: band and settled at {low, high}; steady seconds of each shot (-1 = not steady); idle climbs
        double[][] bandAt = new double[2][2];
        boolean[][] settledAt = new boolean[2][2];
        double[][] steadyAt = new double[2][2 * SHOTS_PER_SPEED];
        double[][] climb = new double[2][IDLE_FRACTIONS.length];
        String[] verdict = new String[2];
        // measurement state
        double inSince = -1, from = -1, target = 0;
        WobbleBand wobbleBand = new WobbleBand();
        int shotIndex = 0, shotPhase = 0, idleIndex = 0, idleLeg = 0;
        double dip = 0, steadyFrom = -1, outSince = -1, stepFrom = -1, spunAt = Double.NaN;
        double[] worstClimb = new double[IDLE_FRACTIONS.length];
        String note = "";

        while (opModeIsActive()) {
            boolean next = gamepad1.crossWasPressed(), fire = gamepad1.rightTriggerWasPressed();
            if (finished) {
                wheels[0].setPower(0);
                wheels[1].setPower(0);
                g.header(0, 0, "Shot-speed check done");
                g.finished("");
                for (int k = 0; k < 2; k++) g.say(sides[k] + ": " + verdict[k]);
                g.update();
                continue;
            }
            DcMotorEx wheel = wheels[side];
            double velocity = wheel.getVelocity();
            double low = speeds[side][0], high = speeds[side][1];
            g.header(0, 0, labels(side) + ": shot-speed check, " + title(step));
            switch (step) {
                case HOLD_LOW:
                case HOLD_HIGH: {
                    int at = step == Step.HOLD_LOW ? 0 : 1;
                    target = at == 0 ? low : high;
                    if (!running) {
                        spin(wheel, p[side], f[side], target);
                        running = true;
                        timer.reset();
                        inSince = -1;
                        from = -1;
                    }
                    double t = timer.seconds();
                    if (from < 0) {
                        boolean near = Math.abs(velocity - target) <= NEAR_SHARE * target;
                        if (!near) inSince = -1;
                        else if (inSince < 0) inSince = t;
                        boolean settled = inSince >= 0 && t - inSince >= NEAR_S;
                        if (settled || t >= SETTLE_MAX_S) {
                            settledAt[side][at] = settled;
                            from = t;
                            wobbleBand = new WobbleBand();
                        }
                        g.say("Waiting for the speed to settle near " + Math.round(target) + " ticks/s...");
                    } else {
                        wobbleBand.add(velocity);
                        g.say("Measuring the wobble...");
                        if (t >= from + MEASURE_S) {
                            bandAt[side][at] = wobbleBand.band(target);
                            running = false;
                            step = at == 0 ? Step.HOLD_HIGH : Step.SHOTS;
                            shotIndex = 0;
                            shotPhase = 0;
                            spunAt = Double.NaN;
                        }
                    }
                    g.value("Target / speed", String.format(Locale.US, "%.0f / %.0f ticks/s", target, velocity));
                    break;
                }
                case SHOTS: {
                    int at = shotIndex < SHOTS_PER_SPEED ? 0 : 1;
                    target = at == 0 ? low : high;
                    // steady = within the band used (never under program 7's); an element reached the wheel = it dipped
                    // past the wobble measured here
                    double b = Math.max(bandAt[side][at], band70[side]), wobble = bandAt[side][at];
                    if (shotPhase == 0) {
                        // loading: L2 runs the intake, R2 fires once the speed is steady (spun up once per speed: setting the
                        // mode again would restart the hub's speed control)
                        if (spunAt != target) {
                            spin(wheel, p[side], f[side], target);
                            spunAt = target;
                        }
                        if (gamepad1.left_trigger > 0.5) intake.in();
                        else intake.stop();
                        g.doThis(String.format(Locale.US, "Shot %d of %d at %.0f ticks/s: hold L2 to load ONE element into this launcher, then R2.",
                                shotIndex + 1, 2 * SHOTS_PER_SPEED, target));
                        if (fire && Math.abs(velocity - target) <= b) {
                            intake.stop();
                            gates[side].setPosition(gate[side][1]);
                            shotTimer.reset();
                            shotPhase = 1;
                            dip = 0;
                            steadyFrom = -1;
                            outSince = -1;
                            note = "";
                        } else if (fire) {
                            note = "wait until the speed is steady, then fire";
                        }
                    } else {
                        double t = shotTimer.seconds();
                        if (shotPhase == 1 && t >= Tuned.gateTravelS) {
                            shotPhase = 2;
                            shotTimer.reset();
                            t = 0;
                        }
                        if (shotPhase == 2) {
                            intake.run(t < AutoRunner.FEED_S ? FEED_TEST_POWER : 0);
                            double error = velocity - target;
                            dip = Math.max(dip, -error);
                            if (Math.abs(error) <= b) {
                                outSince = -1;
                                if (steadyFrom < 0) steadyFrom = t;
                            } else {
                                if (outSince < 0) outSince = t;
                                if (t - outSince >= OUT_BLIP_S) steadyFrom = -1;
                            }
                            if (t >= WATCH_S) {
                                intake.stop();
                                gates[side].setPosition(gate[side][0]);
                                if (dip <= wobble) {
                                    note = "the wheel hardly slowed, so no element reached it: load ONE and fire again";
                                } else {
                                    steadyAt[side][shotIndex] = steadyFrom >= 0 && steadyFrom <= WATCH_S - STEADY_PROOF_S ? steadyFrom : -1;
                                    shotIndex++;
                                }
                                shotPhase = 0;
                                if (shotIndex >= 2 * SHOTS_PER_SPEED) {
                                    step = Step.IDLE;
                                    running = false;
                                    idleIndex = 0;
                                    idleLeg = 0;
                                }
                            }
                        }
                        g.say("Firing and watching the speed...");
                    }
                    g.value("Band at " + Math.round(low) + " / " + Math.round(high) + " ticks/s", String.format(Locale.US, "%.0f / %.0f (program 7's: %.0f)", bandAt[side][0], bandAt[side][1], band70[side]));
                    for (int k = 0; k < shotIndex; k++) {
                        g.value("Shot " + (k + 1), steadyAt[side][k] < 0 ? "not steady in 2 s" : String.format(Locale.US, "steady after %.2f s", steadyAt[side][k]));
                    }
                    g.value("Target / speed", String.format(Locale.US, "%.0f / %.0f ticks/s", target, velocity));
                    break;
                }
                case IDLE: {
                    // per idle candidate: settle there, climb to the low speed; settle again, climb to the high speed
                    double idle = IDLE_FRACTIONS[idleIndex] * low;
                    double goal = idleLeg == 0 ? low : high;
                    if (!running) {
                        spin(wheel, p[side], f[side], idle);
                        running = true;
                        timer.reset();
                        inSince = -1;
                        stepFrom = -1;
                    }
                    double t = timer.seconds();
                    if (stepFrom < 0) {
                        boolean near = Math.abs(velocity - idle) <= Math.max(bandAt[side][0], band70[side]);
                        if (!near) inSince = -1;
                        else if (inSince < 0) inSince = t;
                        if ((inSince >= 0 && t - inSince >= IDLE_SETTLE_S) || t >= IDLE_SETTLE_MAX_S) {
                            spin(wheel, p[side], f[side], goal);
                            stepFrom = t;
                            inSince = -1;
                        }
                    } else {
                        double b = Math.max(bandAt[side][idleLeg], band70[side]);
                        boolean near = Math.abs(velocity - goal) <= b;
                        if (!near) inSince = -1;
                        else if (inSince < 0) inSince = t;
                        boolean arrived = inSince >= 0 && t - inSince >= ARRIVED_S;
                        if (arrived || t - stepFrom >= IDLE_UP_MAX_S) {
                            double up = arrived ? inSince - stepFrom : IDLE_UP_MAX_S;
                            if (idleLeg == 0) {
                                climb[side][idleIndex] = up;
                                idleLeg = 1;
                            } else {
                                worstClimb[idleIndex] = Math.max(climb[side][idleIndex], up);
                                idleLeg = 0;
                                idleIndex++;
                            }
                            running = false;
                            if (idleIndex >= IDLE_FRACTIONS.length) {
                                step = Step.RESULT;
                                verdict[side] = decide(g, sides[side], low, high, band70[side], bandAt[side], settledAt[side], steadyAt[side], worstClimb);
                                wheel.setPower(0);
                            }
                        }
                    }
                    if (step == Step.IDLE) {
                        g.say("Trying idle speeds: settle at the idle, then time the climb to each shot speed...");
                        g.value("Idle tried", String.format(Locale.US, "%.0f%% of the lowest shot speed (%.0f ticks/s), to %s", 100 * IDLE_FRACTIONS[idleIndex], idle, idleLeg == 0 ? "the lowest" : "the highest"));
                    }
                    break;
                }
                default: {
                    g.say(verdict[side]);
                    g.value("Band at " + Math.round(low) + " / " + Math.round(high) + " ticks/s", String.format(Locale.US, "%.0f / %.0f (program 7's: %.0f)", bandAt[side][0], bandAt[side][1], band70[side]));
                    g.keys("cross = " + (side == 0 ? "next: the back flywheel" : "finish"));
                    if (next) {
                        if (side == 0) {
                            side = 1;
                            step = Step.HOLD_LOW;
                            running = false;
                        } else {
                            finished = true;
                        }
                    }
                    break;
                }
            }
            if (!note.isEmpty()) g.warn(note);
            g.update();
        }
        wheels[0].setPower(0);
        wheels[1].setPower(0);
        intake.stop();
    }

    // the checks; saves what passes and says why for the rest
    private static String decide(Guide g, String side, double low, double high, double band70, double[] band, boolean[] settled, double[] steady, double[] worstClimb) {
        int pick = FlywheelAutoTune.chooseIdle(IDLE_FRACTIONS, worstClimb, IDLE_CAP);
        double idle = Math.round(IDLE_FRACTIONS[pick] * low / 10) * 10.0;
        g.record(side + "IdleVelocity", idle);
        String idleText = String.format(Locale.US, " Idle %.0f ticks/s (%.0f%% of the lowest shot speed; climbs %.2f s at worst).", idle, 100 * IDLE_FRACTIONS[pick], worstClimb[pick]);
        if (!settled[0] || !settled[1]) return "Band per speed NOT saved: the speed did not settle within 5% at " + (settled[0] ? "the highest" : "the lowest") + " shot speed. Check for rubbing." + idleText;
        if (band[0] > BAND_MAX_SHARE * low || band[1] > BAND_MAX_SHARE * high) return "Band per speed NOT saved: a band is over 10% of its speed (a wobbly wheel)." + idleText;
        double near = Math.abs(band70 - band[0]) < Math.abs(band70 - band[1]) ? band[0] : band[1];
        boolean between = band70 >= Math.min(band[0], band[1]) - 1e-9 && band70 <= Math.max(band[0], band[1]) + 1e-9;
        if (!between && Math.abs(band70 - near) > BAND_FIT * near) return String.format(Locale.US, "Band per speed NOT saved: program 7's band (%.0f) does not fit between %.0f and %.0f. Run program 7 again first.", band70, band[0], band[1]) + idleText;
        for (int k = 0; k < steady.length; k++) {
            if (steady[k] < 0) return "Band per speed NOT saved: shot " + (k + 1) + " was not steady within 2 s with its band." + idleText;
        }
        double use0 = Math.max(band[0], band70), use1 = Math.max(band[1], band70);
        boolean different = Math.abs(use1 - use0) > BAND_DIFFERENT * Math.min(use0, use1);
        double bLow = different ? use0 : band70, bHigh = different ? use1 : band70;
        g.record(side + "ReadyBandLow", bLow);
        g.record(side + "ReadyBandHigh", bHigh);
        g.record(side + "ReadyBandLowSpeed", low);
        g.record(side + "ReadyBandHighSpeed", high);
        return (different ? String.format(Locale.US, "Band per speed SAVED: %.0f at %.0f ticks/s, %.0f at %.0f ticks/s.", bLow, low, bHigh, high)
                : String.format(Locale.US, "The two bands are within 25%% of each other: one band is enough (%.0f at both ends, saved).", band70)) + idleText;
    }

    private static String labels(int side) {
        return side == 0 ? "FRONT flywheel (NECTAR)" : "BACK flywheel (POLLEN)";
    }

    private static String title(Step s) {
        switch (s) {
            case HOLD_LOW: return "1 hold the lowest shot speed";
            case HOLD_HIGH: return "2 hold the highest shot speed";
            case SHOTS: return "3 recovery shots at both";
            case IDLE: return "4 idle speed against both";
            default: return "result";
        }
    }

    private static void spin(DcMotorEx wheel, double p, double f, double ticksPerSecond) {
        wheel.setMode(DcMotor.RunMode.RUN_USING_ENCODER);
        wheel.setVelocityPIDFCoefficients(p, p / 10, 0, f);
        wheel.setVelocity(ticksPerSecond);
    }

    private DcMotorEx motor(String name, boolean reversed) {
        DcMotorEx m = hardwareMap.get(DcMotorEx.class, name);
        m.setDirection(reversed ? DcMotorSimple.Direction.REVERSE : DcMotorSimple.Direction.FORWARD);
        m.setMode(DcMotor.RunMode.RUN_WITHOUT_ENCODER);
        m.setZeroPowerBehavior(DcMotor.ZeroPowerBehavior.FLOAT);
        return m;
    }
}
